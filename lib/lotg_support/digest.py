def _to_float(value) -> Optional[float]:
    """Parse a cell to float, or None for sentinels / unparseable values."""
    if value is None:
        return None
    if isinstance(value, float) and math.isnan(value):
        return None
    s = str(value).strip()
    if s in _MISSING:
        return None
    s = s.replace(",", "").rstrip("%")
    try:
        return float(s)
    except ValueError:
        return None


def _place(rank: int, end: str) -> str:
    """"highest" / "lowest" for 1st, "2nd-highest" and so on below it.

    "1st-highest" says the same thing twice — "highest" already means first — and
    the doubling is loudest on exactly the lines that matter most. Ranks below
    first still need the ordinal to mean anything."""
    end_word = "highest" if end == "high" else "lowest"
    return end_word if rank == 1 else f"{_ordinal(rank)}-{end_word}"


def _ordinal(n: int) -> str:
    if 10 <= (n % 100) <= 20:
        suf = "th"
    else:
        suf = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suf}"


def _fmt(value: float) -> str:
    """Compact number render: ints as grouped ints, else 1 decimal."""
    if abs(value - round(value)) < 1e-9:
        return f"{int(round(value)):,}"
    out = f"{value:,.1f}"
    # A tiny negative renders "-0.0", which reads as a signed zero rather than a
    # small number. The sign carries no information once the magnitude has
    # rounded away, so drop it.
    return out[1:] if out in ("-0.0", "-0") else out


# Columns stored as a 0-1 fraction under a "%" (or "rate") name — "% of points
# from WRs", every "Win %" — found from the data by `note_percent_columns`. They
# print ×100 with a "%", so 0.104 reads "10.4%" instead of rounding to "0.1".
# Columns stored 0-100 ("% of starters boom") are left as they are.
_PERCENT_COLUMNS: set = set()


def note_percent_columns(frames: dict) -> set:
    """Record which "%" / "rate" columns hold 0-1 fractions in EVERY sheet that
    carries them (a name that is 0-100 anywhere is left alone), and return them."""
    fraction, scaled = set(), set()
    for df in (frames or {}).values():
        if df is None or getattr(df, "empty", True):
            continue
        for c in df.columns:
            name = str(c).lower()
            if "%" not in name and not name.endswith(" rate"):
                continue
            s = numeric_series(df, c)
            if len(s) < 2:
                continue
            (fraction if s.abs().quantile(0.99) <= 1.5 else scaled).add(str(c))
    _PERCENT_COLUMNS.clear()
    _PERCENT_COLUMNS.update(fraction - scaled)
    return set(_PERCENT_COLUMNS)


def _fmt_stat(column: Optional[str], value: float) -> str:
    """`_fmt`, as a percentage when `column` is a 0-1 fraction column."""
    if column is not None and column in _PERCENT_COLUMNS:
        return f"{_fmt(value * 100)}%"
    return _fmt(value)


