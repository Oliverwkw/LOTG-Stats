# Phrasing catalog (the reviewable "how every stat is phrased" CSV)
# ---------------------------------------------------------------------------
def phrasing_catalog(
    player_all_time: pd.DataFrame,
    team_all_time: pd.DataFrame,
    player_year: pd.DataFrame,
    team_year: pd.DataFrame,
    league_year: pd.DataFrame,
    league_all_time: Optional[pd.DataFrame] = None,
    player_week: Optional[pd.DataFrame] = None,
    team_week: Optional[pd.DataFrame] = None,
    league_week: Optional[pd.DataFrame] = None,
    non_rookie_picks: Optional[pd.DataFrame] = None,
    rookie_picks: Optional[pd.DataFrame] = None,
    trades: Optional[pd.DataFrame] = None,
    add_drops: Optional[pd.DataFrame] = None,
    player_additions: Optional[pd.DataFrame] = None,
) -> List[dict]:
    """One row per (sheet, stat) describing exactly how a change is phrased."""
    rows: List[dict] = []

    def _add(sheet, stat, scope, scale, rise, fall):
        rows.append({"sheet": sheet, "stat": stat, "scope": scope, "scale": scale,
                     "phrase_when_rises": rise, "phrase_when_falls": fall})

    def _board_rows(sheet, df):
        """Every numeric column of a row-level sheet, ranked over every row ever."""
        if df is None or df.empty or sheet not in _BOARD_SHEETS:
            return
        mirrored = mirrored_columns(df, sheet)
        for col in discover_numeric_columns(df, _BOARD_SHEETS[sheet]["entity"]):
            note = (" — mirrored, ranked once per event: the positive side, plus "
                    "one row of every dead-even one") if col in mirrored else ""
            _add(sheet, col, f"all-time board (top/bottom 5 of every row ever{note})", "n/a",
                 f"<row> passes <other> for <N>th-highest {col} (<value>).",
                 f"<row> passes <other> for <N>th-lowest {col} (<value>).")

    def _weekly_rows(sheet, df, entity_col, who):
        if df is None or df.empty:
            return
        mirrored = mirrored_columns(df, sheet)
        for col in discover_numeric_columns(df, entity_col):
            if col in mirrored:
                _add(sheet, col, "single-week record (mirrored: one row per event)", "n/a",
                     f"{who}'s {col} this week (<value>) is the <N>th-highest single week ever.",
                     f"{who}'s {col} this week (<value>) is the <N>th-closest to zero ever.")
                continue
            _add(sheet, col, "single-week record (top/bottom 5 of all weeks ever)", "n/a",
                 f"{who}'s {col} this week (<value>) is the <N>th-highest single week ever.",
                 f"{who}'s {col} this week (<value>) is the <N>th-lowest single week ever.")

    def _crossing_rows(sheet, df, entity_col, who, scope):
        for col in discover_numeric_columns(df, entity_col):
            _add(sheet, col, scope, "n/a",
                 f"{who} passes <other> for <N>th-highest {col} all-time (<value>).",
                 f"{who} passes <other> for <N>th-lowest {col} all-time (<value>).")

    def _pace_rows(sheet, df, entity_col, who, window_note):
        for col in discover_numeric_columns(df, entity_col, extra_skip=("Year",)):
            if is_weekly_counting_stat(col):
                # Weekly-counting (awards, result-flips) can't be projected, so
                # they alert when the season's actual value sets a new all-time
                # single-season record instead.
                _add(sheet, col, "yearly record (new single-season high, any year)", "n/a",
                     f"{who} sets a new single-season record for {col} (<value>) — most in any season.",
                     "")
                continue
            scale = "as-is (rate/level)" if is_rate_stat(col) else "scaled by weeks played"
            _add(sheet, col, f"yearly on-pace (from week {MIN_YEARLY_WEEK}; {window_note})", scale,
                 f"{who} is on pace for <N>th-highest {col} this season (<value>).",
                 f"{who} is on pace for <N>th-lowest {col} this season (<value>).")

    # player_all_time: top/bottom 5. team_all_time: any movement among the 8.
    _crossing_rows("player_all_time", player_all_time, "Player", "<player>",
                   "all-time change (top/bottom 5)")
    _crossing_rows("team_all_time", team_all_time, "Team", "<team>",
                   "all-time change (any movement among the 8)")

    _pace_rows("player_year", player_year, "Player", "<player>", "top/bottom 5")
    _pace_rows("team_year", team_year, "Team", "<team>", "top/bottom 5")
    _pace_rows("league_year", league_year, "Year", "The league",
               "top/bottom floor(#seasons/3), capped at 5")

    # Weekly sheets also carry the this-week records, on top of their boards.
    _weekly_rows("player_week", player_week, "Player", "<player>")
    _weekly_rows("team_week", team_week, "Team", "<team>")
    _weekly_rows("league_week", league_week, "Year", "The league")

    # Every row-level sheet is on an all-time board: seasons, weeks, and events.
    for _sheet, _df in (("player_year", player_year), ("team_year", team_year),
                        ("league_year", league_year), ("player_week", player_week),
                        ("team_week", team_week), ("league_week", league_week),
                        ("non_rookie_picks", non_rookie_picks),
                        ("rookie_picks", rookie_picks), ("trades", trades),
                        ("add_drops", add_drops),
                        ("player_additions", player_additions)):
        _board_rows(_sheet, _df)

    # league_all_time: milestones only (single-row sheet, no leaderboard).
    if league_all_time is not None and not league_all_time.empty:
        for col in MAJOR_LEAGUE_STATS:
            if col in league_all_time.columns:
                _add("league_all_time", col, "milestone (round-number crossing)", "n/a",
                     f"League {col} passes <round number> (now <value>).", "")
    return rows


def write_phrasing_csv(path: Path, rows: Sequence[dict]) -> None:
    df = pd.DataFrame(rows, columns=[
        "sheet", "stat", "scope", "scale", "phrase_when_rises", "phrase_when_falls",
    ])
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)


