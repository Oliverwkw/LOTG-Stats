# HTML render
# ---------------------------------------------------------------------------
def _heading(title: str, level: int = 2) -> str:
    if level >= 3:
        return (f'  <h3 style="font:600 16px/1.3 system-ui,sans-serif;'
                f'margin:16px 0 6px;color:#1a2b3c;">{title}</h3>\n')
    return (f'  <h2 style="font:600 18px/1.3 system-ui,sans-serif;'
            f'margin:24px 0 8px;color:#1a2b3c;">{title}</h2>\n')


def _section_html(title: str, lines: Sequence[str], level: int = 2) -> str:
    if not lines:
        return ""
    items = "\n".join(f"      <li>{ln}</li>" for ln in lines)
    return (
        _heading(title, level)
        + f'    <ul style="margin:0;padding-left:20px;'
        f'font:15px/1.5 system-ui,sans-serif;color:#333;">\n{items}\n    </ul>\n'
    )


# Reading order inside a section: PLACE first, then how much the stat matters.
# A 1st-place move is the only place anyone remembers, so every 1st comes before
# every 2nd whatever it is on; within one place, the stats the league argues
# about come before the diagnostics. `stat_relevance` is the lede's own table —
# the summary at the top and the list below it should agree about what matters,
# and two tables would drift apart.
#
# The only placeless item is a league milestone — a threshold crossing, not a
# position on a board — so it sorts last on place, which inside the milestone
# section (its only home) just means it orders by relevance. Everything else
# carries a real place, single-season records included: those are 1st by
# construction, and treating them as placeless used to sink the strongest claim
# in the email below every 5th-place shuffle it shared a section with.
#
# The trailing key parts only make the order stable: an email that reshuffled
# equal items between builds would show up as movement in the audit's diff.
_NO_PLACE = 99


def _order_key(item) -> tuple:
    rank = getattr(item, "rank", None)
    place = int(rank) if isinstance(rank, int) else _NO_PLACE
    # Milestones name their stat `stat`, everything else names it `column`.
    column = str(getattr(item, "column", None) or getattr(item, "stat", "") or "")
    return (place, -stat_relevance(column), column, item.sentence())


def _ucfirst(text: str) -> str:
    """Capitalise the first letter and nothing else — `str.capitalize` lowercases
    the rest, which turns "highest Number of Add/Drops" into "…number…"."""
    return text[:1].upper() + text[1:] if text else text


def _line_of(item) -> str:
    """The item as the SECTION prints it — `line()` where it differs from
    `sentence()`, which is only where the standalone framing restates the
    header."""
    return getattr(item, "line", item.sentence)()


def _label_is_the_header(title: str, group: str) -> bool:
    """True when a section is one entity's and the header already names it.

    Only fires on the league sections, by construction: "Season-long results —
    league" holds nothing but "The league", so labelling its bullets "The
    league:" prints the header a second time. A teams section suffixed "teams"
    never matches an entity called "Oliverwkw"."""
    suffix = title.rsplit("—", 1)[-1].strip().lower().rstrip("s")
    name = group.strip().lower()
    name = name[4:] if name.startswith("the ") else name
    return bool(suffix) and suffix == name


def _grouped_section_html(title: str, items: Sequence, level: int = 2) -> str:
    """Group items by their .group() so one entity's many items read as
    "<entity>:" + an indented sub-list, instead of an endless flat list. A group
    with a single item stays inline (its full line()).

    The label is the bare entity and a colon. It used to carry a verb — "made
    these all-time moves", "had these single-week records" — which was the
    section header said twice, one line apart. The sub-list's own wording
    already supplies the verb where one is needed.

    A group stays together and takes the position of its BEST item: breaking one
    up to interleave its 3rd-place move with someone else's would cost the reader
    the one thing the grouping buys them — seeing everything one entity did in a
    single place."""
    if not items:
        return ""
    groups: "Dict[str, list]" = {}
    for it in items:
        groups.setdefault(it.group(), []).append(it)
    ordered = []
    for g, its in groups.items():
        its.sort(key=_order_key)
        ordered.append((_order_key(its[0]), g, its))
    ordered.sort(key=lambda t: t[0])
    lines = []
    for _key, g, its in ordered:
        if _label_is_the_header(title, g):
            # One entity, already named by the header: its items are the section.
            # Nesting them under an empty label would print a bullet with nothing
            # in it and indent everything below it for no reason.
            lines.extend(_ucfirst(i.detail()) + "." for i in its)
        elif len(its) == 1:
            lines.append(_line_of(its[0]))
        else:
            sub = "".join(
                f'<li style="margin:0;">{i.detail()}</li>' for i in its)
            lines.append(
                f'{g}:'
                f'<ul style="margin:2px 0 6px;padding-left:20px;color:#555;">{sub}</ul>')
    return _section_html(title, lines, level)


def _proj_lines(projections: Sequence[Projection], section: str) -> List[str]:
    return [p.sentence() for p in projections if p.section == section]


def _meta_date(meta: dict) -> Optional[str]:
    """The snapshot's capture date as "August 4, 2026", or None if unparseable."""
    try:
        dt = datetime.fromisoformat(str(meta.get("captured_at") or ""))
    except ValueError:
        return None
    return f"{dt:%B} {dt.day}, {dt.year}"


def digest_title(meta: dict) -> str:
    """The digest's one-line title — the email subject AND the HTML header, so
    the two always agree.

    In-season it names the week ("2026 season, week 7"). In the offseason there
    is no week to name — "week 0" was both meaningless and misleading — so it
    names the date the digest was built instead ("2026 season, August 4, 2026").
    """
    season = meta.get("season")
    week = int(meta.get("weeks_completed") or 0)
    if week >= 1:
        return f"LOTG weekly digest — {season} season, week {week}"
    date = _meta_date(meta)
    return (f"LOTG weekly digest — {season} season, {date}" if date
            else f"LOTG weekly digest — {season} season")


def digest_sections(
    crossings: Sequence[Crossing] = (),
    projections: Sequence[Projection] = (),
    milestones: Sequence[Milestone] = (),
    records: Sequence[YearlyRecord] = (),
    highlights: Sequence[WeeklyHighlight] = (),
    events: Sequence["EventCrossing"] = (),
) -> List[Tuple[str, bool, list]]:
    """(title, grouped, items) for every non-empty digest section, in email order.

    The single place the digest's shape is declared. `render_digest_html` walks
    it to build the email and `email_summary` walks it to write the lede, so a
    new section appears in both by being added here and nowhere else — the lede
    can't silently stop covering a section the email grew.

    `grouped` is whether one entity's several items collapse under a single
    "<entity>:" label; a flat section prints one line each. Milestones are the
    only flat kind — a league total crossing a round number has no entity to
    group by.
    """
    def sect(sec):
        return [x for x in projections if x.section == sec]

    # In-season shows projections as "on pace"; a completed-season wrap resolves
    # them to final results ("finished Nth"), so the heading changes to match.
    yr_final = any(getattr(p, "final", False) for p in projections)
    yr_title = "Season-long results" if yr_final else "On pace this season"

    hl_weeks = sorted({h.week for h in highlights if h.week})
    hl_title = ("Single-week records (this week)" if len(hl_weeks) <= 1
                else f"Single-week records (weeks {hl_weeks[0]}-{hl_weeks[-1]})")

    out: List[Tuple[str, bool, list]] = [
        (hl_title, True, list(highlights)),
        ("All-time leaderboard moves — players", True,
         [c for c in crossings if c.section == "players"]),
        ("All-time leaderboard moves — teams", True,
         [c for c in crossings if c.section == "teams"]),
        ("New single-season records", True, list(records)),
        ("League milestones", False, list(milestones)),
        (f"{yr_title} — players", True, sect("players")),
        (f"{yr_title} — teams", True, sect("teams")),
        (f"{yr_title} — league", True, sect("league")),
    ]
    # One section per board sheet, in _BOARD_SHEETS order.
    # This week's week-board moves ride on the single-week records
    # (`fold_week_boards`), so what is left on a week board is an earlier week.
    out += [(f"All-time leaderboard moves — "
             f"{'earlier ' if sheet in _WEEK_SHEETS else ''}{cfg['title']}", True,
             [e for e in events if e.sheet == sheet])
            for sheet, cfg in _BOARD_SHEETS.items()]
    return [(t, g, items) for t, g, items in out if items]


# The edits section: a header, one sentence of what it means, then the same
# sections the email already has, in the same order, one level down.
EDIT_SECTION_TITLE = "Changes from edits, not new data"
EDIT_SECTION_NOTE = (
    "Everything below moved only because LOTG changed how it computes or records "
    "its history (a code or data fix), not because of anything that happened in "
    "the league since the last digest. A move new data could also explain is "
    "listed above instead.")
_EDIT_HEADER_HTML = (
    '  <h2 style="font:600 18px/1.3 system-ui,sans-serif;margin:32px 0 4px;'
    'padding-top:16px;border-top:2px solid #d0d7de;color:#1a2b3c;">'
    f'{EDIT_SECTION_TITLE}</h2>\n'
    '  <p style="font:14px/1.5 system-ui,sans-serif;color:#555;margin:0 0 8px;">'
    f'{EDIT_SECTION_NOTE}</p>')


def split_sections(sections: Sequence[Tuple[str, bool, list]],
                   new_data: Optional[NewData]
                   ) -> Tuple[List[Tuple[str, bool, list]], List[Tuple[str, bool, list]]]:
    """(new-data sections, edit sections): each section's items split by
    `attribute`, empty halves dropped, order kept. With no `new_data` the edits
    half is always empty and the email is exactly what it was."""
    top, edits = [], []
    for title, grouped, items in sections:
        tags = [attribute(i, title, new_data) for i in items]
        new = [i for i, t in zip(items, tags) if t == "new"]
        old = [i for i, t in zip(items, tags) if t != "new"]
        if new:
            top.append((title, grouped, new))
        if old:
            edits.append((title, grouped, old))
    return top, edits


def _section_block(title: str, grouped: bool, items: Sequence, level: int = 2) -> str:
    if grouped:
        return _grouped_section_html(title, items, level)
    return _section_html(title, [_line_of(i) for i in sorted(items, key=_order_key)],
                         level)


def render_digest_html(
    crossings: Sequence[Crossing],
    projections: Sequence[Projection],
    meta: dict,
    milestones: Sequence[Milestone] = (),
    records: Sequence[YearlyRecord] = (),
    highlights: Sequence[WeeklyHighlight] = (),
    header: Optional[str] = None,
    intro: str = "",
    events: Sequence["EventCrossing"] = (),
    new_data: Optional[NewData] = None,
) -> str:
    if header is None:
        header = digest_title(meta)

    body = [
        '<div style="max-width:680px;margin:0 auto;padding:16px;">',
        f'  <h1 style="font:700 22px/1.3 system-ui,sans-serif;'
        f'color:#0b2545;margin:0 0 4px;">{header}</h1>',
        (f'  <p style="font:16px/1.5 system-ui,sans-serif;color:#0b2545;'
         f'margin:0 0 8px;padding:12px 14px;background:#f2f6fb;'
         f'border-left:3px solid #0b2545;border-radius:4px;">{intro}</p>'
         if intro else ""),
    ]
    # New data first, exactly as it has always read; then, only if there are
    # any, the moves an edit alone explains, under their own header at the
    # bottom (see `attribute`).
    top, edits = split_sections(digest_sections(
        crossings, projections, milestones, records, highlights, events), new_data)
    for title, grouped, items in top:
        body.append(_section_block(title, grouped, items))
    if edits:
        body.append(_EDIT_HEADER_HTML)
        for title, grouped, items in edits:
            body.append(_section_block(title, grouped, items, level=3))
    if not any([highlights, crossings, records, milestones, projections, events]):
        body.append('  <p style="font:15px system-ui,sans-serif;color:#666;">'
                     'No leaderboard changes this week.</p>')
    body.append("</div>")
    return "\n".join(b for b in body if b)


def digest_is_empty(crossings, projections, milestones=(), records=(),
                    highlights=(), events=()) -> bool:
    return not any([crossings, projections, milestones, records, highlights, events])


def _champion_of(team_year: pd.DataFrame, season: int) -> Optional[str]:
    if team_year.empty or "Result" not in team_year.columns:
        return None
    yr = pd.to_numeric(team_year["Year"], errors="coerce")
    sub = team_year[(yr == season) & team_year["Result"].astype(str).str.contains("hampion", na=False)]
    return str(sub.iloc[0]["Team"]) if len(sub) else None


def build_replica_html(frames: dict, season: Optional[int] = None,
                       week: Optional[int] = None) -> str:
    """The offseason seed for the test email — deliberately MINIMAL.

    A real digest reports "changes to the top/bottom-5 of every stat since the
    previous email", which needs a previous email's snapshot. In the offseason
    there is none, and the derived all-time / year rollups can't be reconstructed
    for a single past week from the final exports. So rather than fake it, the
    offseason test email is a short confirmation (champion of the last season).
    During the season, the test button replays the last REAL weekly email instead,
    which is complete. Returns "" if no completed season is on record."""
    tw = frames.get("team_week", pd.DataFrame())
    if season is None or week is None:
        sw = latest_completed_season_week(tw)
        if sw is None:
            return ""
        season, week = sw
    champ = _champion_of(frames.get("team_year", pd.DataFrame()), season)
    intro = (f"🏆 {champ} won the {season} championship." if champ
             else f"The {season} season is complete.")
    note = ("This is the offseason, so there are no week-over-week changes to "
            "report yet. During the season, each Tuesday email lists every change "
            "to the top/bottom 5 of every stat since the previous week.")
    return (f'<div style="max-width:680px;margin:0 auto;padding:16px;'
            f'font:15px/1.5 system-ui,sans-serif;color:#333;">'
            f'<h1 style="font:700 22px/1.3 system-ui,sans-serif;color:#0b2545;'
            f'margin:0 0 8px;">LOTG digest — {season} season wrap</h1>'
            f'<p style="color:#0b2545;font-size:16px;margin:0 0 8px;">{intro}</p>'
            f'<p style="color:#666;margin:0;">{note}</p></div>')


