# On-pace projections
# ---------------------------------------------------------------------------
@dataclass
class Projection:
    section: str        # "players" | "teams" | "league"
    entity: str
    column: str
    end: str            # "high" | "low"
    rank: int
    total: int
    projected: float
    final: bool = False  # season complete -> "finished Nth" instead of "on pace"
    tied: bool = False   # the projected value is shared on the board

    def group(self) -> str:
        return "The league" if self.section == "league" else self.entity

    def name(self) -> str:
        return display_column(self.column, _SECTION_SHEET.get(("year", self.section), ""))

    def detail(self) -> str:
        return (f"{_place(self.rank, self.end)} {self.name()} "
                f"({_fmt_stat(self.column, self.projected)}){_tie(self.tied)}")

    def sentence(self) -> str:
        val = f"{_fmt_stat(self.column, self.projected)}){_tie(self.tied)}"
        if self.final:
            return (f"{self.group()} finished with the {_place(self.rank, self.end)} "
                    f"{self.name()} of any season ({val}.")
        return (f"{self.group()} is on pace for {_place(self.rank, self.end)} "
                f"{self.name()} this season ({val}.")


def _is_boolean(values: Sequence[float]) -> bool:
    """True if every value is 0 or 1 — a per-season flag that can't be projected
    'on pace' (e.g. #363's 'Rostered by champion?')."""
    return bool(values) and all(v in (0.0, 1.0) for v in values)


def _season_horizon(week_frame: pd.DataFrame, current: int) -> Optional[int]:
    """Full-season week count = max week seen in a completed prior season."""
    if week_frame.empty or "Year" not in week_frame.columns or "Week" not in week_frame.columns:
        return None
    years = pd.to_numeric(week_frame["Year"], errors="coerce")
    weeks = pd.to_numeric(week_frame["Week"], errors="coerce")
    prior_max = 0
    for y in sorted({int(v) for v in years.dropna().unique() if int(v) < current}):
        wk = weeks[years == y].dropna()
        if len(wk):
            prior_max = max(prior_max, int(wk.max()))
    return prior_max or None


def _project_frame(
    section: str,
    year_df: pd.DataFrame,
    entity_col: str,
    season: int,
    scale: float,
    window: int,
) -> List[Projection]:
    """Project every numeric yearly column for one sheet and keep the notable
    (top/bottom window) projections ranked against completed seasons."""
    cols = discover_numeric_columns(year_df, entity_col, extra_skip=("Year",))
    year_num = pd.to_numeric(year_df["Year"], errors="coerce")
    curr = year_df[year_num == season]
    hist = year_df[year_num < season]

    projections: List[Projection] = []
    for col in cols:
        if is_weekly_counting_stat(col):
            continue  # awards / result-flip tallies -> actual-value records path
        hist_vals = [v for v in (_to_float(x) for x in hist[col]) if v is not None]
        if len(hist_vals) < window:      # need a meaningful pool to rank against
            continue
        rate = is_rate_stat(col)
        # Project each current entity, then rank ALL entity-seasons (history +
        # this season's projections) together by competition rank, skipping any
        # value shared by more than _MAX_HIGHLIGHT_TIES (how 0/1 flags and
        # heavily-tied stats fall out) or tied past the window (`_tie_fits`).
        proj_by_entity = []
        for _, r in curr.iterrows():
            cur = _to_float(r[col])
            if cur is None:
                continue
            entity = str(r[entity_col]) if entity_col in year_df.columns else str(season)
            proj_by_entity.append((entity, cur if rate else cur * scale))
        if not proj_by_entity:
            continue
        pool = hist_vals + [p for _, p in proj_by_entity]
        counts = _Counter(pool)
        # Competition ranks, as every other board: a tie takes up its places.
        high_rank = competition_ranks(pool, "high")
        low_rank = competition_ranks(pool, "low")
        total = len(pool)
        for entity, projected in proj_by_entity:
            if counts[projected] > _MAX_HIGHLIGHT_TIES:
                continue
            tied = counts[projected] > 1
            if high_rank[projected] <= window:
                if _tie_fits(high_rank[projected], counts[projected], window):
                    projections.append(Projection(section, entity, col, "high",
                                                  high_rank[projected], total, projected,
                                                  tied=tied))
            elif low_rank[projected] <= window and _tie_fits(low_rank[projected],
                                                              counts[projected], window):
                projections.append(Projection(section, entity, col, "low",
                                              low_rank[projected], total, projected,
                                              tied=tied))
    return projections


def _league_window(league_year: pd.DataFrame) -> int:
    """league_year on-pace window = floor(#seasons / 3), capped at 5. With few
    seasons on record the league board is tiny, so the window shrinks with it."""
    if league_year.empty or "Year" not in league_year.columns:
        return 0
    n_seasons = pd.to_numeric(league_year["Year"], errors="coerce").dropna().nunique()
    return min(LEAGUE_WINDOW_CAP, n_seasons // 3)


def project_on_pace(
    player_year: pd.DataFrame,
    team_year: pd.DataFrame,
    league_year: pd.DataFrame,
    team_week: pd.DataFrame,
    min_week: int = MIN_YEARLY_WEEK,
) -> List[Projection]:
    """On-pace projections across player / team / league yearly sheets, per the
    per-section windows (players/teams top/bottom 5; league floor(#seasons/3)≤5).
    Weekly-counting stats (awards, result-flips) are excluded. Empty before
    `min_week` completed weeks, in the offseason, or before a completed prior
    season exists.
    """
    season = current_season(team_year)
    if season is None:
        return []
    played = weeks_completed(team_week, season)
    horizon = _season_horizon(team_week, season)
    if played < min_week or not horizon or played >= horizon:
        return []
    scale = horizon / played

    out: List[Projection] = []
    out += _project_frame("players", player_year, "Player", season, scale,
                          PROJECTION_WINDOW["players"])
    out += _project_frame("teams", team_year, "Team", season, scale,
                          PROJECTION_WINDOW["teams"])
    lw = _league_window(league_year)
    if lw >= 1 and not league_year.empty and "Year" in league_year.columns:
        out += _project_frame("league", league_year, "Year", season, scale, lw)
    return out


def pace_rank_map(projections: Sequence[Projection]) -> dict:
    """Compact {section: {stat: {entity: 'end:rank'}}} for snapshotting the
    on-pace standing, so next week can report only the ones that MOVED."""
    out: Dict[str, Dict[str, Dict[str, str]]] = {}
    for p in projections:
        out.setdefault(p.section, {}).setdefault(p.column, {})[p.entity] = f"{p.end}:{p.rank}"
    return out


def diff_pace(prior_pace: dict, projections: Sequence[Projection]) -> List[Projection]:
    """On-pace projections whose notable rank CHANGED since last week (or newly
    entered the top/bottom window). An entity that unchanged its standing is
    silent — this is what keeps the over-inclusive digest to a readable size."""
    changed: List[Projection] = []
    for p in projections:
        prior = prior_pace.get(p.section, {}).get(p.column, {}).get(p.entity)
        if prior != f"{p.end}:{p.rank}":
            changed.append(p)
    return changed


# ---------------------------------------------------------------------------
# Yearly records (for the weekly-counting stats that DON'T get on-pace)
# ---------------------------------------------------------------------------
# Weekly-counting stats (awards, result-flips) can't be projected "on pace", so
# instead we alert when the current season's ACTUAL value sets a new all-time
# single-season record — the most that stat has ever been in ANY season. Booleans
# are excluded (a 0/1 "record" is meaningless — those surface via all-time counts).
@dataclass
class YearlyRecord:
    section: str        # "players" | "teams" | "league"
    entity: str
    column: str
    value: float

    # A record is only emitted when the value beats every completed season
    # (`_records_for_frame`), so it is 1st place on that stat's all-time
    # single-season board — by construction, not by convention. Saying so keeps
    # it sorting alongside every other 1st place instead of behind them; the
    # prose already carries the claim ("most in any season"), which is why the
    # sentence doesn't repeat it as an ordinal.
    rank: int = 1
    tied: bool = False   # more than one entity set it this season

    def group(self) -> str:
        return "The league" if self.section == "league" else self.entity

    def name(self) -> str:
        return display_column(self.column, _SECTION_SHEET.get(("year", self.section), ""))

    def detail(self) -> str:
        return f"{self.name()} ({_fmt_stat(self.column, self.value)})"

    def sentence(self) -> str:
        return (f"{self.group()} sets a new single-season record for {self.name()} "
                f"({_fmt_stat(self.column, self.value)}) — most in any season"
                f"{_tie(self.tied)}.")

    def line(self) -> str:
        # The header already says "New single-season records"; saying it again
        # and then adding "most in any season" states one fact three times.
        return f"{self.group()}: {self.detail()} — most in any season{_tie(self.tied)}."


def _records_for_frame(section: str, year_df: pd.DataFrame,
                       entity_col: str, season: int) -> List[YearlyRecord]:
    if year_df.empty or "Year" not in year_df.columns:
        return []
    year_num = pd.to_numeric(year_df["Year"], errors="coerce")
    curr = year_df[year_num == season]
    hist = year_df[year_num < season]
    out: List[YearlyRecord] = []
    for col in discover_numeric_columns(year_df, entity_col, extra_skip=("Year",)):
        if not is_weekly_counting_stat(col):
            continue  # records here are only for the not-on-pace weekly stats
        hist_vals = [v for v in (_to_float(x) for x in hist[col]) if v is not None]
        if not hist_vals:
            continue  # need completed seasons to define a record to beat
        pairs = [(str(r[entity_col]) if entity_col in year_df.columns else str(season),
                  _to_float(r[col])) for _, r in curr.iterrows()]
        pairs = [(e, v) for e, v in pairs if v is not None]
        if not pairs:
            continue
        hist_max = max(hist_vals)
        curr_max = max(v for _, v in pairs)
        if curr_max <= hist_max:
            continue  # no new record this season
        holders = [e for e, v in pairs if abs(v - curr_max) < 1e-9]
        if len(holders) > _MAX_HIGHLIGHT_TIES:
            continue  # >5 tied for the "record" -> not notable (the >5-tied rule)
        for e in holders:
            out.append(YearlyRecord(section, e, col, curr_max, tied=len(holders) > 1))
    return out


def yearly_records(player_year: pd.DataFrame, team_year: pd.DataFrame,
                   league_year: pd.DataFrame, team_week: pd.DataFrame,
                   min_week: int = MIN_RECORD_WEEK,
                   season: Optional[int] = None) -> List[YearlyRecord]:
    """New all-time single-season records set by weekly-counting stats. Defaults
    to the current season (from its first completed week: a record is the HIGH
    end of a count, real the week it happens); pass an explicit `season` (e.g. a
    finished season) to skip the week gate."""
    if season is None:
        season = current_season(team_year)
        if season is None or weeks_completed(team_week, season) < min_week:
            return []
    out: List[YearlyRecord] = []
    out += _records_for_frame("players", player_year, "Player", season)
    out += _records_for_frame("teams", team_year, "Team", season)
    if not league_year.empty and "Year" in league_year.columns:
        out += _records_for_frame("league", league_year, "Year", season)
    return out


def record_value_map(records: Sequence[YearlyRecord]) -> dict:
    """{section: {stat: record_value}} snapshot so next week only re-reports a
    record when it's been beaten/extended, not every week it stands."""
    out: Dict[str, Dict[str, float]] = {}
    for r in records:
        out.setdefault(r.section, {})[r.column] = r.value
    return out


def diff_records(prior_map: dict, records: Sequence[YearlyRecord]) -> List[YearlyRecord]:
    """Records that are newly set or have grown past last week's record value."""
    changed: List[YearlyRecord] = []
    for r in records:
        prev = prior_map.get(r.section, {}).get(r.column)
        if prev is None or r.value > prev + 1e-9:
            changed.append(r)
    return changed


# ---------------------------------------------------------------------------
# Weekly single-week highlights (the WEEKLY sheets: player/team/league_week)
# ---------------------------------------------------------------------------
# Rank the just-completed week's single-week values against EVERY week ever, and
# surface the ones landing in the top/bottom `WINDOW` — "best/worst single week
# of all time" alerts. This is how the weekly sheets get directly involved in the
# digest (they otherwise only feed the year/all-time rollups). Booleans (per-week
# award flags) are skipped — their tallies show via the year/all-time paths.

# A single-week value shared by more than this many week-rows is too common to be
# a "record" (e.g. the pile of 0s on percentile / streak columns, or a routinely
# tied max), so it's skipped on BOTH ends. Genuine extremes are near-unique.
_MAX_HIGHLIGHT_TIES = 5


# Two spellings, on purpose:
#   sentence()  stands alone — the lede quotes it, and a lede that needs its
#               section header to make sense is no use at the top of the email.
#   line()      is what the SECTION prints, where the header has already said
#               where you are. Default: the same string. Overridden only where
#               the standalone framing would restate the header word for word.
@dataclass
class WeeklyHighlight:
    section: str        # "players" | "teams" | "league"
    entity: str
    column: str
    end: str            # "high" | "low"
    rank: int           # among every DISTINCT single-week value on record
    value: float
    # Which week this performance is FROM. Normally the digest's own week, so it
    # goes unsaid. It is said out loud only when a digest is covering more than
    # one week — i.e. when a previous week's run never happened and this one is
    # making up the gap (see build_digest.py). Highlights are the one part of the
    # digest that is NOT self-healing across a missed week: the crossing/record/
    # pace/event diffs all compare STATE against the prior snapshot and so report
    # a two-week move whole, but a single-week performance belongs to its week and
    # is simply never mentioned again once that week's digest is skipped.
    week: Optional[int] = None
    show_week: bool = False
    # Another week on record holds the same value: "highest ever (tie)".
    tied: bool = False
    # Who the week-board move behind this record passed or tied, named (see
    # `fold_week_boards`): "— lowest ever, tied with Kyle Pitts".
    others: tuple = ()
    passed: tuple = ()
    # This week's opponent, on a stat measured against him (`_OPPONENT_MARKERS`).
    opponent: str = ""
    # Others who set the same value THIS week — one line for the lot
    # (`fold_week_boards`): "Kaleb Johnson and Kyle Pitts: ... — lowest ever (tie)".
    co_entities: tuple = ()

    def group(self) -> str:
        if self.section == "league":
            return "The league"
        return _name_list((self.entity,) + tuple(self.co_entities))

    def _value(self) -> str:
        """"75", or "75 vs LWebs53" on a stat measured against the opponent."""
        v = _fmt_stat(self.column, self.value)
        return f"{v} vs {self.opponent}" if self.opponent else v

    def _name(self) -> str:
        return display_column(self.column, _SECTION_SHEET.get(("week", self.section), ""))

    def _against(self) -> str:
        """", tied with X" / ", passing X and Y" — or "(tie)" when a tie is not
        named (three or more holders)."""
        rel = f", tied with {_name_list(self.others)}" if self.others else _tie(self.tied)
        return rel + (f", passing {_name_list(self.passed)}" if self.passed else "")

    def detail(self) -> str:
        wk = f" [week {self.week}]" if self.show_week and self.week else ""
        return (f"{self._name()} ({self._value()}) — "
                f"{_place(self.rank, self.end)} ever{self._against()}{wk}")

    def sentence(self) -> str:
        if self.co_entities:
            return (f"{self.group()} share the {_place(self.rank, self.end)} "
                    f"{self._name()} of any single week ({self._value()})"
                    f"{self._against()}.")
        return (f"{self.group()}'s {self._name()} this week "
                f"({self._value()}) is the "
                f"{_place(self.rank, self.end)} single week ever{self._against()}.")

    def line(self) -> str:
        # "…'s Points this week (55) is the highest single week ever" under a
        # header that already reads "Single-week records (this week)".
        if self.co_entities:
            return f"{self.group()}: {self.detail()}."
        return f"{self.group()}'s {self.detail()}."


def latest_completed_week(team_week: pd.DataFrame, season: int) -> Optional[int]:
    if team_week.empty or "Year" not in team_week.columns or "Week" not in team_week.columns:
        return None
    sub = team_week[pd.to_numeric(team_week["Year"], errors="coerce") == season]
    weeks = pd.to_numeric(sub["Week"], errors="coerce").dropna()
    return int(weeks.max()) if len(weeks) else None


def latest_completed_season_week(team_week: pd.DataFrame) -> Optional[tuple]:
    """The most recent completed (season, week) across ALL seasons — i.e. the
    last week that has games on record (the championship week of the latest
    finished season in the offseason). Drives the 'most recent digest' replica."""
    if team_week.empty or "Year" not in team_week.columns:
        return None
    years = pd.to_numeric(team_week["Year"], errors="coerce").dropna()
    if not len(years):
        return None
    season = int(years.max())
    week = latest_completed_week(team_week, season)
    return (season, week) if week else None


def _highlights_for_frame(section: str, wk_df: pd.DataFrame, entity_col: str,
                          season: int, week: int, window: int,
                          sheet: str = "") -> List[WeeklyHighlight]:
    if wk_df.empty or "Year" not in wk_df.columns or "Week" not in wk_df.columns:
        return []
    year = pd.to_numeric(wk_df["Year"], errors="coerce")
    wknum = pd.to_numeric(wk_df["Week"], errors="coerce")
    this_week = wk_df[(year == season) & (wknum == week)]
    if this_week.empty:
        return []
    has_entity = entity_col in wk_df.columns

    mirrored = mirrored_columns(wk_df, sheet)
    # A running total is not a week's performance. Its value hops onto the newest
    # row of a run every week, so it re-read "highest ever" week after week (Dak
    # Prescott's 102 weeks on team, a streak one longer than last week). The
    # all-time week boards still carry them, compared player to player.
    running = running_columns(wk_df)
    out: List[WeeklyHighlight] = []
    for col in discover_numeric_columns(wk_df, entity_col):
        if col in running:
            continue
        pool = rankable_series(wk_df, col, col in mirrored, sheet)
        all_vals = pool.tolist()
        if len(all_vals) < window:
            continue
        ranked_rows = set(pool.index)
        # Both ends (some stats go negative, so "lowest ever" is meaningful).
        # Rank by DISTINCT value so ties share a rank; the ONLY exclusion is a
        # value shared by more than _MAX_HIGHLIGHT_TIES rows (that's how booleans
        # and heavily-tied cumulative extremes fall out — per the >5-tied rule).
        counts = _Counter(all_vals)
        # Competition ("1224") ranks so tied weeks take up the requisite slots:
        # a two-way tie for the record makes the next value the 3rd-best ever.
        high_rank = competition_ranks(all_vals, "high")
        low_rank = competition_ranks(all_vals, "low")
        for _, r in this_week.iterrows():
            v = _to_float(r[col])
            # The row test covers the unranked half of a mirrored column: the
            # pool holds one row per event, so the loser's -M isn't ranked (the
            # same fact is already reported from the winner's row) and neither is
            # the second row of a tie, whose 0 the kept row already carries.
            if v is None or r.name not in ranked_rows or counts[v] > _MAX_HIGHLIGHT_TIES:
                continue
            entity = str(r[entity_col]) if has_entity else "The league"
            tied = counts[v] > 1
            if high_rank[v] <= window:
                if _tie_fits(high_rank[v], counts[v], window):
                    out.append(WeeklyHighlight(section, entity, col, "high", high_rank[v], v,
                                               week=int(week), tied=tied))
            elif low_rank[v] <= window and _tie_fits(low_rank[v], counts[v], window):
                out.append(WeeklyHighlight(section, entity, col, "low", low_rank[v], v,
                                           week=int(week), tied=tied))
    return out


def weekly_highlights(player_week: pd.DataFrame, team_week: pd.DataFrame,
                      league_week: pd.DataFrame, team_year: pd.DataFrame,
                      window: int = WINDOW,
                      season: Optional[int] = None,
                      week: Optional[int] = None) -> List[WeeklyHighlight]:
    """Top/bottom-`window` single-week performances in a completed week, ranked
    against every week on record. Defaults to the current season's latest week
    (empty in the offseason); pass explicit season/week for a past week."""
    if season is None:
        season = current_season(team_year)
    if season is None:
        return []
    if week is None:
        week = latest_completed_week(team_week, season)
    if not week:
        return []
    out: List[WeeklyHighlight] = []
    out += _highlights_for_frame("players", player_week, "Player", season, week, window,
                                 sheet="player_week")
    out += _highlights_for_frame("teams", team_week, "Team", season, week, window,
                                 sheet="team_week")
    out += _highlights_for_frame("league", league_week, "Year", season, week, window,
                                 sheet="league_week")
    return out


# ---------------------------------------------------------------------------
# All-time boards (every row-level sheet)
# ---------------------------------------------------------------------------
# A sheet's rows are its records: a pick, a trade, a transaction — but equally
# one player's season, one team's week. Every numeric column of every such sheet
# is ranked over EVERY row of that sheet ever, and the top/bottom `WINDOW` are
# snapshotted. Week over week the board is diffed and read out in the same
# "X passes Y for Nth-highest …" sentence as the player / team all-time boards,
# because it is the same news: a place on a leaderboard changed hands.
#
# Covering every season (not just the in-progress one) is what makes a recompute
# of HISTORY reportable. A rolling KTC window crossing an anniversary, or a
# formula change, re-values a 2023 trade into the all-time O-Score top 5 — the row
# that moved is a past-season row, and a board holding only the current season's
# rows produced no item at all.


@dataclass
class EventHighlight:
    sheet: str          # "picks" | "trades" | "add_drops"
    label: str          # human name of the event (e.g. "2025 pick 1.01 (…)")
    column: str
    end: str            # "high" | "low"
    rank: int
    value: float
    key: str = ""       # stable row identity (see _event_row_key); NOT the label
    # A running-total column (see `running_columns`): the row that carries the
    # total changes as the run grows, so the diff compares `entity` — whose run
    # it is (`_row_entity`) — rather than the row.
    running: bool = False
    entity: str = ""

    def group(self) -> str:
        return self.label

    def detail(self) -> str:
        return (f"{display_column(self.column, self.sheet)} of "
                f"{_fmt_stat(self.column, self.value)} —"
                f"{_place(self.rank, self.end)} of any {self.sheet[:-1]} ever")

    def sentence(self) -> str:
        return (f"{self.label}: {display_column(self.column, self.sheet)} of "
                f"{_fmt_stat(self.column, self.value)} —"
                f"{_place(self.rank, self.end)} of any {self.sheet[:-1]} ever.")


def _event_cell(row, col) -> str:
    v = row.get(col) if hasattr(row, "get") else None
    return "" if v is None or (isinstance(v, float) and math.isnan(v)) else str(v)


# How many assets a trade label names before it stops listing them. The longest
# deal on record received 12 (330 characters); a subject line's worth is enough
# to recognise the deal, and the sheet holds the full list.
_LABEL_ASSETS = 3


def _asset_summary(raw: str) -> str:
    """"A; B; C; D" -> "A, B, C +1 more" — the assets a side of a deal received."""
    parts = [a.strip() for a in str(raw).split(";") if a.strip()]
    if not parts:
        return ""
    shown = ", ".join(parts[:_LABEL_ASSETS])
    extra = len(parts) - _LABEL_ASSETS
    return f"{shown} +{extra} more" if extra > 0 else shown


def _whole(text: str) -> str:
    """'2023.0' -> '2023'; anything else unchanged."""
    return text[:-2] if re.fullmatch(r"-?\d+\.0", text or "") else text


def _board_label(sheet: str, row) -> str:
    """How a row is named in the email. Season / week rows are named by entity and
    when; event rows name what actually moved (the assets)."""
    def g(c):
        return _event_cell(row, c)
    # Dates carry a timestamp for uniqueness; the label only needs the day. (The
    # row KEY still uses the full value — see _board_row_key.)
    day = lambda c: g(c)[:10]
    if sheet == "player_year":
        return f"{g('Player')} {g('Year')}".strip()
    if sheet == "team_year":
        return f"{g('Team')} {g('Year')}".strip()
    if sheet == "league_year":
        # league_year has no text column, so a row taken from it is a float64
        # Series and Year arrives as "2023.0" — which the email printed ("the
        # 2023.0 season passes the 2022.0 season", run 497). Only the LABEL is
        # cleaned: the row KEY keeps the stored spelling ("league_year|2023.0",
        # _board_row_key) so a committed baseline still lines up, and an old
        # baseline's labels are read through migrate_board_label.
        return f"the {_whole(g('Year'))} season".strip()
    if sheet == "player_week":
        return f"{g('Player')} {g('Year')} week {g('Week')}".strip()
    if sheet == "team_week":
        return f"{g('Team')} {g('Year')} week {g('Week')}".strip()
    if sheet == "league_week":
        return f"{g('Year')} week {g('Week')}".strip()
    if sheet in _PICK_SHEETS:
        return f"{g('Year')} pick {g('Number')} ({g('Player Picked')})".strip()
    if sheet == "trades":
        # Name what the team got: "whose trade" alone doesn't say what moved, and
        # a team can make several deals on one day.
        got = _asset_summary(g("Assets received"))
        head = f"{g('Team')}'s {day('Date')} trade"
        return f"{head} for {got}" if got else head
    if sheet == "add_drops":
        added, dropped = g("Player Added"), g("Player Dropped")
        # The date disambiguates: one team can pick the same player up twice, and
        # two board lines reading "LWebs53's move for Jeff Wilson" are unreadable.
        head = f"{g('Team')}'s {day('Date')}"
        if added:
            return f"{head} move for {added}".strip()
        return f"{head} drop of {dropped}".strip() if dropped else f"{head} move"
    if sheet == "player_additions":
        # Every row of this sheet is an ACQUISITION, so the preposition has to
        # say the player arrived. "<Team>'s <date> trade of <Player>" said the
        # opposite — it reads as trading him away — which on a board line like
        # "AceMatthew's 2025-06-18 trade of Bijan Robinson: KTC at end of season
        # of 9713 — 1st-highest" told the league the exact reverse of what
        # happened. A trade is the one type where the wrong preposition is not
        # merely awkward but false, so it gets "for".
        #
        # The rest read as an acquisition once the noun the comment always
        # promised is actually there: "waiver of X" is not English, "waiver
        # pickup of X" is. A draft is already a noun that takes "of", so it is
        # left alone rather than made into a "draft pickup".
        kind = (g("Addition type") or "").lower()
        who = g("Player")
        if kind == "trade":
            return f"{g('Team')}'s {day('Date')} trade for {who}".strip()
        noun = "draft" if kind == "draft" else f"{kind} pickup".strip()
        return f"{g('Team')}'s {day('Date')} {noun or 'pickup'} of {who}".strip()
    return sheet


# The same rename, applied to a label written by an OLDER build.
#
# A crossing is decided by KEY (`by_key`), and the key holds no label
# ("player_additions|Tom Brady|stevenb123|2025-12-16|Waiver"), so a rename cannot
# by itself invent or silence a line. What the label decides is everything the
# line SAYS about the other rows: `by_rank` supplies the names in "passes …" and
# "joins a tie with …", and `val_by_label` is how `_nobody_moved` asks whether
# the row a mover overtook actually moved. On the live baseline the rename
# rewrites 107 stored labels and all 107 sit in that pool, so without a migration
# two things follow: a sentence names the passed row in last week's spelling
# while the mover carries this week's — the same event under two names, and
# capable of reading as passing itself — and the cascade rule's lookup for those
# rows misses, so a line it should have suppressed prints instead.
#
# Migrating the baseline is therefore part of the rename, not a follow-up. It is
# done on READ, in `_prior_board`, rather than by rewriting the committed
# snapshot: it is idempotent, it costs nothing once the snapshot rotates into the
# new spelling, and it keeps working if an older snapshot is ever replayed. Only
# the spelling of `label` changes; keys, ranks and values are untouched, so the
# diff sees exactly the events it saw before under their new names.
_LEGACY_ADDITION_LABEL = re.compile(
    r"^(?P<head>.+?'s \d{4}-\d{2}-\d{2}) (?P<kind>trade|waiver|free agency|commissioner) of "
    r"(?P<who>.+)$")
# league_year's float year ("the 2023.0 season") — see _board_label.
_LEGACY_SEASON_LABEL = re.compile(r"^the (-?\d+)\.0 season$")


def migrate_board_label(sheet: str, label: str) -> str:
    """An old label in today's spelling (idempotent): player_additions'
    acquisition wording, and league_year's float year."""
    if not isinstance(label, str):
        return label
    if sheet == "league_year":
        return _LEGACY_SEASON_LABEL.sub(r"the \1 season", label)
    if sheet != "player_additions":
        return label
    m = _LEGACY_ADDITION_LABEL.match(label)
    if not m:
        return label                      # already migrated, or a draft label
    head, kind, who = m.group("head"), m.group("kind"), m.group("who")
    if kind == "trade":
        return f"{head} trade for {who}"
    return f"{head} {kind} pickup of {who}"


# The board's row identity. NOT the label — a label is written for a human and
# repeats (the same team picking the same player up twice), which would merge two
# distinct rows into one place on the board and manufacture movement between them
# on every diff. NOT the row index either: inserting one current-season row
# renumbers every later one, which is the same trap the "Link to …" columns fall
# into. `ids` in _BOARD_SHEETS are the sheets' natural keys.
def _board_row_key(sheet: str, row) -> str:
    cols = _BOARD_SHEETS.get(sheet, {}).get("ids")
    if not cols:
        return _board_label(sheet, row)
    return sheet + "|" + "|".join(_event_cell(row, c) for c in cols)


# Every row-level sheet gets a board. A sheet's "events" are its rows: a pick, a
# trade, a transaction — but also one player's season, one team's week. Ranking
# all of them against every row of that sheet ever is what makes the answer to
# "did anything move into the top 5 of anything?" a single mechanism instead of
# one special case per sheet. `entity` is the column discover_numeric_columns
# treats as the row's name (not a stat); `ids` are the natural key; `title` names
# the section in the email.
_BOARD_SHEETS = {
    "player_year":  {"entity": "Player", "ids": ("Player", "Year"),
                     "title": "player seasons"},
    "team_year":    {"entity": "Team", "ids": ("Team", "Year"),
                     "title": "team seasons"},
    "league_year":  {"entity": "Year", "ids": ("Year",),
                     "title": "league seasons"},
    "player_week":  {"entity": "Player", "ids": ("Player", "Year", "Week"),
                     "title": "player weeks"},
    "team_week":    {"entity": "Team", "ids": ("Team", "Year", "Week"),
                     "title": "team weeks"},
    "league_week":  {"entity": "Year", "ids": ("Year", "Week"),
                     "title": "league weeks"},
    # The picks frame ships as two sheets and they get two boards: the startup
    # and the 2021 vet draft are scored in their own percentile universe (and
    # de-trended for draft slot), so ranking them against rookie picks would
    # compare grades that do not mean the same thing.
    "non_rookie_picks": {"entity": "Year", "ids": ("Year", "Number"),
                     "title": "startup & vet draft picks"},
    "rookie_picks": {"entity": "Year", "ids": ("Year", "Number"),
                     "title": "rookie draft picks"},
    "trades":       {"entity": "Season", "ids": ("Team", "Date", "Team's traded with 1"),
                     "title": "trades"},
    "add_drops": {"entity": "Season",
                     "ids": ("Team", "Date", "Player Added", "Player Dropped"),
                     "title": "add/drops"},
    "player_additions": {"entity": "Player",
                     "ids": ("Player", "Team", "Date", "Addition type"),
                     "title": "player additions"},
}


# ---------------------------------------------------------------------------
# Who may stand where yet (the week-5 gates)
# ---------------------------------------------------------------------------
_WEEK_SHEETS = ("player_week", "team_week", "league_week")
_EVENT_SHEETS = ("trades", "add_drops", "player_additions") + _PICK_SHEETS
# player_week tenure columns: an average over the player's CURRENT stint on the
# team, which began with the move that brought him there.
_TENURE_MARKERS = ("on team", "team starter", "by this team")
# Running counts that are not terminal-encoded (see `running_columns`).
_RUNNING_COLUMNS = {"Number of weeks on team", "Age", "Startup draft players remaining"}


def running_columns(df: pd.DataFrame) -> set:
    """A sheet's running-total columns — a value carried forward from one row of
    the same entity to its next rather than describing its own row: every
    terminal-encoded column (a run's total sits on its latest row, every earlier
    row reads "In Progress"), every streak (a week's, a season's "Winning season
    streak"), every "number of times" tally of one team and one player
    ("Number of times picked up by this team"), and the plain running counts in
    `_RUNNING_COLUMNS`. A new row of such a column is the SAME run, so the board
    diff compares it entity to entity (`_row_entity`)."""
    if df is None or df.empty:
        return set()
    out = set()
    for c in df.columns:
        name = str(c)
        low = name.lower()
        if name in _RUNNING_COLUMNS or "streak" in low or "number of times" in low:
            out.add(name)
        # Not `dtype == object`: pandas 3 (what CI installs) reads text as the
        # `str` dtype, which that test never matched — so on run 515 every
        # terminal-encoded total fell out of this set and "Pat Freiermuth 2026
        # week 2 passes Pat Freiermuth 2026 week 1" came back.
        elif not pd.api.types.is_numeric_dtype(df[c]) \
                and (df[c].astype(str).str.strip() == "In Progress").any():
            out.add(name)
    return out


def _row_entity(sheet: str, column: str, row) -> str:
    """Whose run a board row belongs to, for `running_columns`: the player or team
    (a week or season row), the team AND opponent for a head-to-head streak, the
    team AND player for a per-player tally on the transaction sheets, and "" for
    the league."""
    def g(c):
        return _event_cell(row, c)
    low = column.lower()
    if sheet in ("player_week", "player_year"):
        return g("Player")
    if sheet in ("team_week", "team_year"):
        return f"{g('Team')}|{g('Opponent')}" if "opponent" in low else g("Team")
    if sheet == "add_drops":
        who = g("Player Dropped") if "dropped" in low else g("Player Added")
        return f"{g('Team')}|{who}"
    if sheet == "player_additions":
        return f"{g('Team')}|{g('Player')}"
    if sheet in _PICK_SHEETS:
        return g("Player Picked")
    if sheet == "trades":
        return g("Team")
    return ""


def _kickoff_tuesday(season: int) -> date:
    """The Tuesday fantasy week 1 of `season` begins: two days before the
    Thursday after Labor Day — the anchor `_week_tuesday` in src/lotg.py uses
    (the league's week runs Tuesday-Monday)."""
    sept1 = date(int(season), 9, 1)
    labor_day = sept1 + timedelta(days=(0 - sept1.weekday()) % 7)
    return labor_day + timedelta(days=1)


def event_start_week(when, last_weeks: Optional[Dict[int, int]] = None
                     ) -> Optional[Tuple[int, int]]:
    """(season, fantasy week) a dated move is FOR — where its NFL clock starts.

    Weeks run Tuesday-Monday, so a Tuesday waiver claim is for the coming week. A
    move between seasons is for week 1 of the season after it; a January move
    still inside a season's schedule (`last_weeks`: {season: its last week},
    default 17) is for that week. None when the date can't be read — which gates
    nothing."""
    try:
        d = date.fromisoformat(str(when).strip()[:10])
    except ValueError:
        return None
    start = _kickoff_tuesday(d.year)
    if d >= start:
        return d.year, (d - start).days // 7 + 1
    prior_week = (d - _kickoff_tuesday(d.year - 1)).days // 7 + 1
    if prior_week <= (last_weeks or {}).get(d.year - 1, 17):
        return d.year - 1, prior_week
    return d.year, 1


class BoardGate:
    """Which rows may stand where on the all-time boards yet.

    A row still being written stands only on the HIGH end of a counting stat
    (`is_counting_stat`) — a real record the week it happens. Its averages, rates,
    scores, values and low ends wait for a sample:

      * the in-progress season's player/team/league season rows: until the season
        is over. "On pace" (week 5 on) reports them meanwhile.
      * trades, add/drops, pickups and draft picks: until `EVENT_MIN_WEEKS` NFL
        weeks have been played since the move (an offseason move: week 5).
      * player_week: a season-to-date column ("... this season") on the
        in-progress season's rows until week `MIN_YEARLY_WEEK` — then all of them,
        week 1's included; a tenure column ("PPG as team starter") until the stint
        it averages is `EVENT_MIN_WEEKS` weeks old.

    Everything is read off the frames — the season is the latest on team_year, the
    weeks played are team_week's, a season's length the longest before it — so no
    year is named and it turns over to the next season by itself. `lag` pretends
    the last `lag` weeks are unplayed: last week's gate, to see what this week let
    go (`release_lead`)."""

    def __init__(self, frames: dict, lag: int = 0):
        frames = frames or {}
        tw, ty = frames.get("team_week"), frames.get("team_year")
        weeks: List[Tuple[int, int]] = []
        if tw is not None and not tw.empty and {"Year", "Week"} <= set(tw.columns):
            yrs = pd.to_numeric(tw["Year"], errors="coerce")
            wks = pd.to_numeric(tw["Week"], errors="coerce")
            weeks = sorted({(int(a), int(b)) for a, b in zip(yrs, wks)
                            if pd.notna(a) and pd.notna(b)})
        if lag > 0:
            weeks = weeks[:-lag] if lag < len(weeks) else []
        self.weeks = weeks
        self._pos = {yw: i for i, yw in enumerate(weeks)}
        self.last_weeks: Dict[int, int] = {}
        for a, b in weeks:
            self.last_weeks[a] = max(self.last_weeks.get(a, b), b)
        season = current_season(ty) if ty is not None and not ty.empty else None
        if season is None and weeks:
            season = weeks[-1][0]
        self.season = season
        self.played = sum(1 for a, _b in weeks if a == season)
        horizon = max((b for a, b in self.last_weeks.items()
                       if season is not None and a < season), default=None)
        self.season_open = season is not None and not (horizon and self.played >= horizon)
        self._memo: Dict[tuple, Optional["pd.Series"]] = {}
        self._player_week = frames.get("player_week")

    def held_rookies(self) -> set:
        """The in-progress season's rookie class while it is still held (before
        week `ROOKIE_OSCORE_WEEK`) — the players the all-time PLAYER boards keep
        to the high end of a counting stat, as the rookie-pick boards do. Week 2
        of 2026 put Denzel Boston, two games in, on three rate boards ("2nd-highest
        Rostered upper quartile % (50)"). Read off player_week's `Rookie?` flag, so
        an undrafted rookie is held too."""
        pw = self._player_week
        if (not self.season_open or self.played >= ROOKIE_OSCORE_WEEK or pw is None
                or pw.empty or not {"Year", "Player", "Rookie?"} <= set(pw.columns)):
            return set()
        this = pw[pd.to_numeric(pw["Year"], errors="coerce") == self.season]
        rookie = this["Rookie?"].astype(str).str.strip().str.lower().isin({"true", "1", "yes"})
        return set(this.loc[rookie, "Player"].astype(str))

    def elapsed_since(self, start: Tuple[int, int]) -> int:
        """NFL weeks played from `start` (inclusive) through the latest."""
        return len(self.weeks) - bisect_left(self.weeks, tuple(start))

    def _this_season(self, df: pd.DataFrame) -> Optional["pd.Series"]:
        if not self.season_open or "Year" not in df.columns:
            return None
        return pd.to_numeric(df["Year"], errors="coerce") == self.season

    def _young_events(self, df: pd.DataFrame,
                      min_weeks: int = EVENT_MIN_WEEKS) -> Optional["pd.Series"]:
        if not self.weeks:
            return None
        if "Date" in df.columns:
            starts = [event_start_week(d, self.last_weeks) for d in df["Date"]]
        elif "Year" in df.columns:          # a draft pick: its season's week 1
            starts = []
            for y in df["Year"]:
                yv = _to_float(y)
                starts.append((int(yv), 1) if yv is not None else None)
        else:
            return None
        return pd.Series([s is not None and self.elapsed_since(s) < min_weeks
                          for s in starts], index=df.index)

    def _young_stints(self, df: pd.DataFrame) -> Optional["pd.Series"]:
        if not self.weeks or not {"Year", "Week", "Number of weeks on team"} <= set(df.columns):
            return None
        n = len(self.weeks)
        young = []
        for y, w, k in zip(pd.to_numeric(df["Year"], errors="coerce"),
                           pd.to_numeric(df["Week"], errors="coerce"),
                           pd.to_numeric(df["Number of weeks on team"], errors="coerce")):
            if pd.isna(y) or pd.isna(w) or pd.isna(k):
                young.append(False)
                continue
            start = self._pos.get((int(y), int(w)), n) - (int(k) - 1)
            young.append(n - start < EVENT_MIN_WEEKS)
        return pd.Series(young, index=df.index)

    def restricted(self, df: pd.DataFrame, sheet: str, column: str) -> Optional["pd.Series"]:
        """Rows of `df` held to the high end of `column` when it counts, and off
        every end when it does not. None when no row is held."""
        if sheet in _YEARLY_SHEETS:
            kind = "season"
        elif sheet in _EVENT_SHEETS:
            kind = "event"
        elif sheet == "player_week":
            c = column.lower()
            if "this season" in c:
                if self.played >= MIN_YEARLY_WEEK:
                    return None
                kind = "season"
            elif any(m in c for m in _TENURE_MARKERS):
                kind = "stint"
            else:
                return None
        else:
            return None
        # This year's rookie class waits for the week the build first grades it
        # (its O-Score, `ROOKIE_OSCORE_WEEK`), not the five weeks a trade or
        # pickup does: week 1 of 2026 put ten picks on the boards off one game.
        weeks = ROOKIE_OSCORE_WEEK if sheet == "rookie_picks" else EVENT_MIN_WEEKS
        key = (id(df), kind, weeks)
        if key not in self._memo:
            if kind == "event":
                self._memo[key] = self._young_events(df, weeks)
            else:
                self._memo[key] = {"season": self._this_season,
                                   "stint": self._young_stints}[kind](df)
        return self._memo[key]


def _carry_held_runs(df: pd.DataFrame, column: str, s: "pd.Series",
                     held: "pd.Series") -> "pd.Series":
    """Keep a season streak's completed run on the board while the season it has
    run on into is held back.

    A streak that continues into the in-progress season moves its total onto that
    season's row and leaves "In Progress" on the season before. Holding the new
    row back (`BoardGate`) would therefore take the whole run off the board, and
    every row below it would climb a place standing still — on week 1 of 2026,
    "plehv79 2020 joins a tie for 5th-highest Winning season streak (1)". So the
    run's completed length — the held row's value less the one season it adds —
    goes back on the row before, as it read before the season began."""
    ent_col = next((c for c in ("Team", "Player") if c in df.columns), None)
    if ent_col is None or "Year" not in df.columns:
        return s
    held = held.reindex(df.index, fill_value=False).astype(bool)
    held_idx = [i for i in df.index[held] if i in s.index]
    if not held_idx:
        return s
    years = pd.to_numeric(df["Year"], errors="coerce")
    row_of = {(str(e), int(y)): i for i, e, y in zip(df.index, df[ent_col], years) if pd.notna(y)}
    extra = {}
    for i in held_idx:
        if s[i] < 1:
            continue
        prev = row_of.get((str(df.at[i, ent_col]), int(years[i]) - 1))
        if prev is not None and prev not in s.index \
                and str(df.at[prev, column]).strip() == "In Progress":
            extra[prev] = float(s[i]) - 1
    return pd.concat([s, pd.Series(extra, dtype=float)]) if extra else s


def _board_places(pool: "pd.Series", end: str, window: int,
                  max_ties: int) -> Dict[float, int]:
    """value -> competition rank, for the values holding a top/bottom-`window`
    place in `pool` (a value shared by more than `max_ties` rows holds none)."""
    if len(pool) < window:
        return {}
    counts = pool.value_counts()
    return {v: r for v, r in competition_ranks(pool.tolist(), end).items()
            if r <= window and counts[v] <= max_ties and _tie_fits(r, counts[v], window)}


def board_highlights(df: pd.DataFrame, sheet: str, window: int = WINDOW,
                     max_ties: int = _MAX_HIGHLIGHT_TIES,
                     gate: Optional[BoardGate] = None) -> List[EventHighlight]:
    """The top/bottom-`window` rows of every numeric column on one sheet, ranked
    against every row of that sheet ever (mirrored columns: positive side only).

    Ranks are COMPETITION ranks over values (Change 4): tied rows take up the
    requisite number of the top-N slots, so a two-way tie for 1st makes the next
    value 3rd. A value shared by more than `max_ties` rows is not a record and is
    left off the board — but it still occupies its slots, so the places below it
    keep their numbering.

    `gate` holds rows still being written to the high end of a counting stat (see
    `BoardGate`); they are ranked nowhere else, so the places they would have
    taken go to rows with a sample. Without a gate every row ranks everywhere."""
    cfg = _BOARD_SHEETS.get(sheet)
    if cfg is None or df is None or df.empty:
        return []
    mirrored = mirrored_columns(df, sheet)
    running = running_columns(df)
    out: List[EventHighlight] = []
    for col in discover_numeric_columns(df, cfg["entity"]):
        s = rankable_series(df, col, col in mirrored, sheet)
        if len(s) < window:
            continue
        held = gate.restricted(df, sheet, col) if gate is not None else None
        if held is not None and col in running and sheet in _YEARLY_SHEETS:
            s = _carry_held_runs(df, col, s, held)
        lo_s = s
        if held is not None:
            held = held.reindex(s.index, fill_value=False).astype(bool)
            if held.any():
                lo_s = s[~held]
        hi_s = s if is_counting_stat(col) else lo_s
        # A season-accumulating count's LOW end is left to the on-pace projection,
        # not ranked on the all-time board — "fewest pure drops" is a preseason
        # artifact, not a record. Only its HIGH end stays here.
        low_on_board = not (sheet in _YEARLY_SHEETS and is_yearly_counting_stat(col))
        hi = _board_places(hi_s, "high", window, max_ties)
        # The high end wins when a value qualifies at both (a short board where
        # the top and bottom five overlap).
        lo = ({v: r for v, r in _board_places(lo_s, "low", window, max_ties).items()
               if v not in hi} if low_on_board else {})
        if not hi and not lo:
            continue
        place: Dict[object, tuple] = {}
        if hi:
            for idx, v in hi_s[hi_s.isin(list(hi))].items():
                place[idx] = ("high", hi[v])
        if lo:
            for idx, v in lo_s[lo_s.isin(list(lo))].items():
                place.setdefault(idx, ("low", lo[v]))
        for idx, value in s[s.index.isin(list(place))].items():
            row = df.loc[idx]
            end, rank = place[idx]
            is_run = col in running
            out.append(EventHighlight(sheet, _board_label(sheet, row), col,
                                      end, rank, float(value),
                                      _board_row_key(sheet, row),
                                      running=is_run,
                                      entity=_row_entity(sheet, col, row) if is_run else ""))
    return out


def all_board_highlights(frames: dict, window: int = WINDOW,
                         gate: Optional[BoardGate] = None) -> List[EventHighlight]:
    """Every board across every sheet that has rows to rank — what the weekly
    digest snapshots and diffs. `gate` holds back rows still being written (see
    `BoardGate`); without one every row ranks everywhere."""
    out: List[EventHighlight] = []
    for sheet in _BOARD_SHEETS:
        out += board_highlights(frames.get(sheet, pd.DataFrame()), sheet, window, gate=gate)
    return out


# The sheets where a brand-new ROW means a real new event — a trade or add just
# made, a pick freshly recorded — so "this key was in no prior snapshot" is worth
# knowing. The per-week / per-season aggregate sheets are excluded: a new row
# there is just the calendar advancing, already told by the live/in-season split,
# and tracking their every key would bloat the snapshot for no signal.
_NEW_ROW_SHEETS = _PICK_SHEETS + ("trades", "add_drops", "player_additions")


# ---------------------------------------------------------------------------
# New data vs edits
# ---------------------------------------------------------------------------
# The email puts every move an EDIT alone explains — a code or curated-data
# change re-valuing settled history — in its own section at the bottom, and
# everything new data could explain (including a move both touched) where it has
# always been. Two pieces of evidence decide it, both gathered here:
#
#   did an edit land at all?   `edit_fingerprint` hashes the build's inputs as
#       committed (git's blob ids for src/, lib/, data/, config/league.yaml), so
#       the next digest can compare. Paths that bots commit every week are left
#       out — the gameday injury sweeps, the digest's own snapshot, the audit
#       baseline — and so are the digest-rendering modules, which change the
#       email but not a single exported value.
#   what arrived since the last digest?   `new_data_since`: the weeks completed
#       since then, the players and teams in them, and — kept apart — the players
#       and teams in brand-new transaction rows.
EDIT_INPUT_ROOTS = ("src/", "lib/", "data/", "config/league.yaml")
EDIT_INPUT_EXCLUDES = (
    "data/injury_tracker.csv", "data/digest/", "data/audit/",
    "lib/lotg_support/digest.py", "lib/lotg_support/email_summary.py",
    "lib/lotg_support/mailer.py",
)
_TRANSACTION_TEAM_COLS = ("Team", "Original Team", "Team's traded with 1",
                          "Team's traded with 2", "Team's traded with 3",
                          "Team's traded with 4")
_TRANSACTION_PLAYER_COLS = ("Player", "Player Added", "Player Dropped",
                            "Player Picked")


def edit_fingerprint(tree_entries: Sequence[str]) -> Optional[str]:
    """A short hash of the build's inputs from `git ls-tree -r` entries
    ("<mode> <type> <sha>\t<path>"). Changes when a tracked input changes and
    for no other reason; None when there are no inputs to hash."""
    import hashlib
    parts = []
    for entry in tree_entries:
        head, _tab, path = str(entry).partition("\t")
        if not path or not path.startswith(EDIT_INPUT_ROOTS) \
                or path.startswith(EDIT_INPUT_EXCLUDES):
            continue
        bits = head.split()
        if len(bits) >= 3:
            parts.append(f"{path} {bits[2]}")
    if not parts:
        return None
    return hashlib.sha256("\n".join(sorted(parts)).encode()).hexdigest()[:16]


def new_data_since(prior: Optional[dict], meta: dict, frames: dict,
                   fingerprint: Optional[str] = None) -> Optional[NewData]:
    """What reached the league between the prior snapshot and this build — None
    with no prior snapshot, when there is nothing to diff at all.

    Weeks count the same way `_weeks_to_cover` does: `weeks_completed` is a COUNT
    of distinct weeks, so the new ones are this season's weeks past the prior
    count (all of them when the season rolled over)."""
    if prior is None:
        return None
    season = meta.get("season")
    pmeta = prior.get("meta", {}) or {}
    new_weeks: set = set()
    tw = frames.get("team_week")
    if season is not None and tw is not None and not tw.empty \
            and {"Year", "Week"} <= set(tw.columns):
        yrs = pd.to_numeric(tw["Year"], errors="coerce")
        have = sorted({int(w) for w in pd.to_numeric(
            tw.loc[yrs == season, "Week"], errors="coerce").dropna()})
        done = (int(pmeta.get("weeks_completed") or 0)
                if pmeta.get("season") == season else 0)
        new_weeks = {(int(season), w) for w in have[done:]}
    players: set = set()
    teams: set = set()
    tx_players: set = set()
    tx_teams: set = set()
    wk_nums = {w for _s, w in new_weeks}
    for sheet, col, bucket in (("player_week", "Player", players),
                               ("team_week", "Team", teams)):
        df = frames.get(sheet)
        if not wk_nums or df is None or df.empty \
                or not {col, "Year", "Week"} <= set(df.columns):
            continue
        sel = ((pd.to_numeric(df["Year"], errors="coerce") == season)
               & pd.to_numeric(df["Week"], errors="coerce").isin(wk_nums))
        bucket.update(str(x) for x in df.loc[sel, col].dropna())
    prior_keys = prior.get("row_keys")
    if prior_keys:
        known = set(prior_keys)
        for sheet in _NEW_ROW_SHEETS:
            df = frames.get(sheet)
            if df is None or getattr(df, "empty", True):
                continue
            for _idx, row in df.iterrows():
                if _board_row_key(sheet, row) in known:
                    continue
                tx_teams.update(v for v in (_event_cell(row, c)
                                            for c in _TRANSACTION_TEAM_COLS) if v)
                tx_players.update(v for v in (_event_cell(row, c)
                                              for c in _TRANSACTION_PLAYER_COLS) if v)
    last_weeks: Dict[int, int] = {}
    if tw is not None and not tw.empty and {"Year", "Week"} <= set(tw.columns):
        _lw = pd.DataFrame({"y": pd.to_numeric(tw["Year"], errors="coerce"),
                            "w": pd.to_numeric(tw["Week"], errors="coerce")}).dropna()
        last_weeks = {int(y): int(w) for y, w in _lw.groupby("y")["w"].max().items()}
    before = pmeta.get("inputs_fingerprint")
    edit_landed = (before != fingerprint) if (before and fingerprint) else None
    return NewData(season=season, weeks_completed=meta.get("weeks_completed"),
                   new_weeks=new_weeks, players=players, teams=teams,
                   edit_landed=edit_landed, tx_players=tx_players,
                   tx_teams=tx_teams, last_weeks=last_weeks)


def all_row_keys(frames: dict) -> List[str]:
    """Every row key on the transaction/pick sheets — the full set, not just the
    ranked places the event board keeps. Stored in the snapshot so next week's
    diff can tell a genuinely NEW row (key absent here) from an old one that
    merely climbed onto a board (key present here, just never top-five before)."""
    keys = set()
    for sheet in _NEW_ROW_SHEETS:
        df = frames.get(sheet)
        if df is None or getattr(df, "empty", True):
            continue
        for _, row in df.iterrows():
            keys.add(_board_row_key(sheet, row))
    return sorted(keys)


# ---------------------------------------------------------------------------
# Mirror detection for the phrasing catalog
# ---------------------------------------------------------------------------
# The email itself no longer needs this: a mirrored column is detected by
# is_mirrored_column and ranked on its positive side like any other. This
# per-matchup form survives only to LABEL such columns in the phrasing catalog.
def two_sided_columns(df: pd.DataFrame, entity_col: str, opp_col: str,
                      id_cols: Sequence[str]) -> List[str]:
    """Numeric columns that are genuinely two-sided: for most events the pair's
    two rows hold mirror values (a ≈ -b). Detected from the data, no name list."""
    if df is None or df.empty or opp_col not in df.columns:
        return []
    out: List[str] = []
    for col in discover_numeric_columns(df, entity_col):
        groups: Dict[tuple, list] = {}
        for _, r in df.iterrows():
            v = _to_float(r[col])
            if v is None:
                continue
            a, b = str(r[entity_col]), str(r.get(opp_col) or "")
            if not b:
                continue
            key = tuple(str(r.get(c, "")) for c in id_cols) + tuple(sorted([a, b]))
            groups.setdefault(key, []).append(v)
        mirror = tot = 0
        for vs in groups.values():
            if len(vs) != 2:
                continue
            mag = max(abs(vs[0]), abs(vs[1]))
            if mag <= 1e-6:
                continue  # a 0/0 pair is trivially "mirrored"; not a real two-sided stat
            tot += 1
            if abs(vs[0] + vs[1]) <= 1e-6 + 0.01 * mag:
                mirror += 1
        if tot >= 3 and mirror / tot >= 0.8:
            out.append(col)
    return out

@dataclass
class EventCrossing:
    """One event overtaking (or joining) a place on an all-time event board.

    Phrased exactly like an all-time player/team `Crossing`. A mover that lands
    alone overtakes whoever held the slot it took — a whole tie at once, named in
    full ("passes X and Y for lowest"). A mover that arrives at a value others
    still hold JOINS the tie instead (named when two-way, summarised otherwise,
    suppressed once the tie exceeds five). Only the mover is reported.
    """
    sheet: str          # "picks" | "trades" | "add_drops"
    label: str          # the mover, named; identity is the row key
    column: str
    end: str            # "high" | "low"
    rank: int
    value: Optional[float]
    joined: bool = False
    others: tuple = ()          # co-holders at the mover's value, when joined
    passed: tuple = ()          # entities overtaken, when not joined
    is_new: bool = False        # the row's key was in NO prior board — a brand-new
    #                             row (a just-made trade/add, a freshly recorded
    #                             pick), not a re-valued or re-ranked old one. A
    #                             renumber does NOT set this: the slot key already
    #                             existed, it just held a different player.
    # The row's own value last week, when it held a place on this board. None
    # when it arrived from off the board (most re-valuations) — see Crossing.
    prev_value: Optional[float] = None
    key: str = ""               # the row key (identity), for `release_lead`
    # Label -> how the email names it, where that differs (an opponent added,
    # `name_opponents`). Display only: `label` stays the identity everything
    # else reads.
    shown: dict = field(default_factory=dict)
    # Other rows that reached the same tie the same week (`merge_simultaneous_ties`).
    co_movers: tuple = ()

    def _show(self, label: str) -> str:
        return self.shown.get(label, label)

    def group(self) -> str:
        return _name_list([self._show(x) for x in (self.label,) + tuple(self.co_movers)])

    def detail(self) -> str:
        return _crossing_detail(self.joined, tuple(map(self._show, self.others)),
                                tuple(map(self._show, self.passed)),
                                _place(self.rank, self.end), self.column, self.value,
                                self.sheet, self.co_movers)

    def sentence(self) -> str:
        return f"{self.group()} {self.detail()}."


def event_board(events: Sequence[EventHighlight]) -> list:
    """The snapshot payload: every place on every event board, with its rank, in
    a stable order so the committed snapshot diffs cleanly week to week."""
    return sorted(
        ({"sheet": e.sheet, "key": e.key, "label": e.label, "column": e.column,
          "end": e.end, "rank": e.rank, "value": e.value,
          # Whose run a running-total place is, so next week's diff can tell a
          # run's new row from a rival (`running_columns`).
          **({"entity": e.entity} if e.running else {})} for e in events),
        key=lambda d: (d["sheet"], d["column"], d["end"], d["rank"], d["key"]))


def _prior_board(prior_board) -> Optional[Dict[tuple, dict]]:
    """Prior board as (sheet, column, end) -> {rank -> place, keys -> {key: rank}}.
    None when it can't be read as a board — including the pre-board snapshot
    format (a list of "sheet|label|col|end:rank" strings), which the caller then
    treats as "no prior", re-baselining in silence instead of reporting the whole
    board as new."""
    if not prior_board:
        return None
    out: Dict[tuple, dict] = {}
    for d in prior_board:
        if not isinstance(d, dict):
            return None
        try:
            slot = out.setdefault((d["sheet"], d["column"], d["end"]),
                                  {"by_rank": {}, "by_key": {}, "val_by_key": {}})
            rank = int(d["rank"])
            slot["by_key"][d["key"]] = rank
            # Last week's value, for the lede's live-vs-recompute split. Absent
            # in an older snapshot, which simply leaves prev_value None.
            if d.get("value") is not None:
                slot["val_by_key"][d["key"]] = d["value"]
            # Every holder of a rank last week, so overtaking a whole tie names
            # all of them (Change 4).
            # Both label lookups read the stored label through the rename, so a
            # baseline written by an older build lines up with this week's
            # spelling instead of looking like a different row. See
            # `migrate_board_label`.
            _label = migrate_board_label(d["sheet"], d.get("label", d["key"]))
            slot["by_rank"].setdefault(rank, []).append(_label)
            # By LABEL too, because `passed` names labels, not keys — needed to
            # ask whether the row a mover overtook actually moved.
            if d.get("value") is not None and d.get("label"):
                slot.setdefault("val_by_label", {})[_label] = d["value"]
            # Whose run a running-total place was (absent in an older snapshot,
            # where the diff reads it off the label instead).
            if d.get("entity") is not None:
                slot.setdefault("entity_by_label", {})[_label] = d["entity"]
        except (KeyError, TypeError, ValueError):
            return None
    # The worst place each board held last week. A row that was NOT on the board
    # and is now got there one of two ways: its own value improved past this
    # cutoff, or the board shortened above it and it was carried in without
    # moving. Only the first is news. See `_nobody_moved`.
    for slot in out.values():
        vals = list(slot["val_by_key"].values())
        slot["cutoff"] = None
        if vals and slot["by_key"]:
            worst_rank = max(slot["by_key"].values())
            worst = [slot["val_by_key"][k] for k, r in slot["by_key"].items()
                     if r == worst_rank and k in slot["val_by_key"]]
            if worst:
                slot["cutoff"] = worst[0]
    return out


def _improved(value: float, other: float, end: str) -> bool:
    """True when `value` is nearer the watched end than `other`."""
    return value > other if end == "high" else value < other


def _nobody_moved(mover_prev: Optional[float], mover_now: float, end: str,
                  cutoff: Optional[float], rivals: Sequence[tuple]) -> bool:
    """True when this crossing reports an order change in which NOTHING moved.

    A leaderboard re-ranks for two different reasons and the email says the same
    sentence for both. Either an entity's value changed — real news — or an
    entity ABOVE it changed and everyone underneath was carried up a place
    without doing anything. The second is a cascade, and it multiplies: on
    2026-09-08 one pick's KTC being restored vacated 1st place on five boards at
    once and the digest reported 23 pick "moves", not one of which had its own
    value change. `2021 pick 3.01 (Mac Jones) passes 2021 pick 2.01 (Justin
    Fields) for 3rd-highest ...` — both numbers identical to last week's, both
    men simply standing still while somebody else fell past them.

    So a crossing survives only if at least one of the entities it NAMES actually
    moved. `rivals` is (prev, now) for each entity passed or tied; an unpriceable
    rival counts as moved, which keeps the line (report rather than swallow).

    A mover with no prior value was off the board. That is the ambiguous case —
    it either improved its way on, or the board shortened above it — and
    `cutoff`, the worst place the board held last week, settles it: better than
    the cutoff means it climbed on under its own power.
    """
    if mover_prev is None:
        if cutoff is None:
            return False                      # unknown vintage -> report
        # Only a value STRICTLY worse than last week's cutoff proves the row did
        # not move: it could not have held a place at that value either, so the
        # board must have shortened above it. Landing exactly ON the cutoff is
        # the opposite — competition ranks put a row tied with the last place ON
        # the board, so a row arriving at that value had to climb to it. Reading
        # the boundary the other way lost `2025 week 4 joins a tie for
        # 5th-highest Number of WR rostered (100)`, whose count really did go
        # 99 -> 100 when the pinned player rejoined the WR pool.
        if not _improved(cutoff, mover_now, end):
            return False                      # at or past last week's cutoff
    elif abs(mover_prev - mover_now) > 1e-9:
        return False                          # the mover's own value changed
    for prev, now in rivals:
        if prev is None or now is None or abs(prev - now) > 1e-9:
            return False                      # a named rival moved (or is unknown)
    return True


def diff_events(prior_board, events: Sequence[EventHighlight],
                prior_row_keys: Optional[Sequence[str]] = None) -> List[EventCrossing]:
    """Overtakes on the event boards since `prior_board`.

    An event is reported when it now holds a place nearer the watched end than it
    held last week — including arriving from off the board entirely, which is how
    a re-valued historical row shows up. `passed` is whoever held that place last
    week; with no one there (the board was shorter), there is no overtake to
    report and the event is skipped.

    A place can also be JOINED rather than taken: ranks are competition ranks
    over values, so co-occupants of a rank hold the same value. If anyone else is
    still standing on the rank the mover arrived at, nobody was displaced and the
    move is a tie-join — named when two-way, summarised for three-to-five, and
    suppressed once the tie exceeds five. Landing alone overtakes every prior
    holder of the slot taken (a whole tie counts as several), named in full."""
    prior = _prior_board(prior_board)
    if prior is None:
        return []
    # A row is brand-new when its key was in the prior snapshot's FULL row set
    # (`prior_row_keys`) — not merely absent from the prior board, which would
    # also catch an old row climbing into the top five for the first time, and a
    # renumber whose slot key just changed hands. Without that set (a pre-upgrade
    # snapshot), nothing can be called new: is_new stays False and the week
    # re-baselines it silently rather than mislabelling re-valuations as new data.
    new_row_keys = set(prior_row_keys) if prior_row_keys else None

    def _is_new(e) -> bool:
        return bool(new_row_keys is not None and e.sheet in _NEW_ROW_SHEETS
                    and e.key not in new_row_keys)
    # Who else stands on each place NOW. Built once, not per event: on a busy
    # week this walks several thousand board places.
    co: Dict[tuple, Dict[int, List[str]]] = {}
    for e in events:
        co.setdefault((e.sheet, e.column, e.end), {}).setdefault(e.rank, []).append(e.key)
    label_of = {(e.sheet, e.column, e.end, e.key): e.label for e in events}
    # Whose run each running-total place on the board NOW is (see `running_columns`).
    entity_now = {(e.sheet, e.column, e.label): (e.entity or _label_entity(e.sheet, e.label))
                  for e in events if e.running}
    # The value each label holds on the board NOW, so an overtake can be tested
    # for whether the reader could see it at all (_indistinguishable).
    value_of_label = {(e.sheet, e.column, e.end, e.label): e.value for e in events}
    rank_of_label = {(e.sheet, e.column, e.end, e.label): e.rank for e in events}
    out: List[EventCrossing] = []
    for e in events:
        slot = prior.get((e.sheet, e.column, e.end))
        if not slot:
            continue
        was = slot["by_key"].get(e.key)
        # A running total's value moves onto the newest row of its run every week
        # (terminal encoding), so the ROW is new while the player is not: "Josh
        # Allen 2026 week 1 passes Josh Allen 2025 week 17". Judge it by the
        # entity's best place last week, and never name its own old rows.
        own = None
        if e.running:
            ent = e.entity or _label_entity(e.sheet, e.label)

            def own(lbl, ent=ent, col=e.column, sheet=e.sheet, slot=slot):
                # Whose run `lbl` is: this week's board says, else last week's
                # snapshot, else (a snapshot older than stored entities) its label.
                known = entity_now.get((sheet, col, lbl))
                if known is None:
                    known = slot.get("entity_by_label", {}).get(lbl)
                if known is None:
                    known = _label_entity(sheet, lbl)
                return known == ent

            mine = [r for r, labels in slot["by_rank"].items() if any(own(x) for x in labels)]
            if mine:
                was = min(mine) if was is None else min(was, min(mine))
        if was is not None and e.rank >= was:
            continue                       # unmoved, or pushed down by someone else
        # A row that arrived from off the board with a value strictly worse than
        # last week's last place did not climb on: the board shortened above it.
        # It stood still, and a row that stood still passes nobody.
        if (not _is_new(e) and slot["val_by_key"].get(e.key) is None and e.value is not None
                and slot.get("cutoff") is not None and not e.running
                and _improved(slot["cutoff"], e.value, e.end)):
            continue
        ck = (e.sheet, e.column, e.end)
        other_keys = [k for k in co[ck][e.rank] if k != e.key]
        if other_keys:
            # Joined a tie. Suppress once it exceeds five holders total.
            if len(other_keys) >= _MAX_JOIN_TIE:
                continue
            others = sorted(label_of.get((e.sheet, e.column, e.end, k), k)
                            for k in other_keys)
            if e.label in others:
                # A different row of the SAME entity already held the place; that
                # is not news about the entity.
                continue
            if own is not None:
                others = [o for o in others if not own(o)]
                if not others:
                    continue
            # A row whose own value did not change joined nothing: the row above
            # it fell to it. That is the faller's news, told from the wrong side.
            _prev_v = slot["val_by_key"].get(e.key)
            if (not _is_new(e) and _prev_v is not None and e.value is not None
                    and not _improved(e.value, _prev_v, e.end)):
                continue
            if not _is_new(e) and _nobody_moved(
                    slot["val_by_key"].get(e.key), e.value, e.end, slot.get("cutoff"),
                    [(slot.get("val_by_label", {}).get(lbl),
                      value_of_label.get((e.sheet, e.column, e.end, lbl))) for lbl in others]):
                continue
            # The places this tie now fills (rank .. rank+k-1) and who held them
            # last week, now standing below the tie or off the board.
            _was = was if was is not None else 10 ** 9
            _last = e.rank + len(others)
            pushed = sorted({
                lbl for r, labels in slot["by_rank"].items()
                if e.rank <= r <= _last and r < _was
                for lbl in labels
                if lbl != e.label and lbl not in others
                and not (own is not None and own(lbl))
                and rank_of_label.get((e.sheet, e.column, e.end, lbl), 10 ** 9) > e.rank})
            out.append(EventCrossing(e.sheet, e.label, e.column, e.end, e.rank,
                                     e.value, joined=True, others=tuple(others),
                                     passed=tuple(pushed),
                                     is_new=_is_new(e),
                                     prev_value=slot["val_by_key"].get(e.key),
                                     key=e.key))
            continue
        # Landed alone: overtook every prior holder of the slot it now occupies —
        # or, when the board shifted under it and they stand ahead of it now,
        # whoever held a board place above its old one and is now behind it.
        passed = [lbl for lbl in slot["by_rank"].get(e.rank, [])
                  if lbl != e.label and not (own is not None and own(lbl))
                  and rank_of_label.get((e.sheet, e.column, e.end, lbl), 10 ** 9) > e.rank]
        if not passed:
            _was = was if was is not None else 10 ** 9
            passed = sorted(
                lbl for r, labels in slot["by_rank"].items() if r < _was
                for lbl in labels
                if lbl != e.label and not (own is not None and own(lbl))
                and rank_of_label.get((e.sheet, e.column, e.end, lbl), 10 ** 9) > e.rank)
        if not passed:
            continue
        # A row that climbed without its own value moving toward this end was
        # carried up by a row above it falling — see `_column_crossings`.
        _prev_v = slot["val_by_key"].get(e.key)
        if (not _is_new(e) and _prev_v is not None and e.value is not None
                and not _improved(e.value, _prev_v, e.end)):
            continue
        # An overtake nobody can see is not news — see _indistinguishable. Only
        # the passed rows still ON the board have a current value to compare; a
        # row pushed off entirely is not evidence either way, so it keeps the
        # move (the conservative direction: report rather than swallow).
        _passed_vals = [value_of_label.get((e.sheet, e.column, e.end, lbl))
                        for lbl in passed]
        if (e.value is not None and all(v is not None for v in _passed_vals)
                and _indistinguishable(e.value, _passed_vals, e.column)):
            continue
        # An overtake in which neither side moved is a cascade, not news — see
        # _nobody_moved. A brand-new row is exempt: it is new data by definition.
        if not _is_new(e) and _nobody_moved(
                slot["val_by_key"].get(e.key), e.value, e.end, slot.get("cutoff"),
                [(slot.get("val_by_label", {}).get(lbl), cur)
                 for lbl, cur in zip(passed, _passed_vals)]):
            continue
        out.append(EventCrossing(e.sheet, e.label, e.column, e.end, e.rank,
                                 e.value, joined=False, passed=tuple(sorted(passed)),
                                 is_new=_is_new(e),
                                 prev_value=slot["val_by_key"].get(e.key),
                                 key=e.key))
    return merge_simultaneous_ties(out)


