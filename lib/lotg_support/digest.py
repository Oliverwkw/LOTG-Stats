def is_counting_stat(column: str) -> bool:
    """A tally or a total — points, games, weeks, moves, FAAB dollars, award
    counts — whose HIGH end is a real record the week it happens. Averages,
    rates, percentiles, scores, values and changes are not: they need a sample."""
    if is_weekly_counting_stat(column):
        return True
    if column in _LEVEL_COLUMNS or is_rate_stat(column):
        return False
    c = column.lower()
    return not any(m in c for m in _LEVEL_MARKERS)


