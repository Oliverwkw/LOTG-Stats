def _indistinguishable(value: float, others: Sequence[float],
                       column: Optional[str] = None) -> bool:
    """True when `value` renders exactly like every one of `others`.

    A crossing is real in the data and unreportable in the email when the mover
    and everyone it overtook print the same number: "2026 pick 4.07 (Darnell
    Mooney) passes 2026 pick 3.02 (Chig Okonkwo) for 2nd-lowest Tanking (-0.0)"
    was decided by 0.0006, four decimal places below what the sentence shows, and
    led the 2026-09-08 digest. The reader is asked to accept an overtake between
    two numbers that are, as printed, the same number.

    Deliberately phrased against the RENDERED string rather than an absolute
    epsilon: the threshold that matters is what the email can actually show, and
    it stays correct if the formatting ever changes. Empty `others` (nobody to be
    indistinguishable from) is False — the move stands.
    """
    others = [o for o in others if o is not None]
    if not others:
        return False
    shown = _fmt_stat(column, value)
    return all(_fmt_stat(column, o) == shown for o in others)


def is_rate_stat(column: str) -> bool:
    """True if a yearly stat is a rate/level (projected as-is, not scaled)."""
    c = column.lower()
    return any(m in c for m in _RATE_MARKERS)


def is_weekly_counting_stat(column: str) -> bool:
    """True for stats that tally a per-week boolean outcome (max one per week) —
    the weekly awards (`Times ...`) and the result-flip counterfactuals
    (`Wins/Losses from hardship`, `Wins/Losses from byes`). These do NOT get an
    on-pace projection (you can't be "on pace for 8.5 awards"); movement on them
    is surfaced only through their all-time crossings (players top/bottom 5,
    teams any-of-8)."""
    c = column.lower()
    return c.startswith("times ") or "wins from" in c or "losses from" in c


