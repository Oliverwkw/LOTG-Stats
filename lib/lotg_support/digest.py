def discover_numeric_columns(df: pd.DataFrame, entity_col: str,
                             extra_skip: Sequence[str] = ()) -> List[str]:
    """Every column that ranks: not a key, and with >= 2 numeric values.

    Record strings ("34-20"), result labels ("Champion"), and team-name columns
    fail float parsing and are dropped automatically, so this stays truly
    over-inclusive without a hand-maintained exclusion list.
    """
    skip = set(_KEY_COLS) | {entity_col} | set(extra_skip)
    cols: List[str] = []
    for c in df.columns:
        if c in skip:
            continue
        numeric = sum(1 for v in df[c] if _to_float(v) is not None)
        if numeric >= 2:
            cols.append(c)
    return cols


# ---------------------------------------------------------------------------
# Mirrored (zero-centred) columns
# ---------------------------------------------------------------------------
# Some columns hold the SAME fact twice with opposite signs: a matchup's margin
# is +M for the winner and -M for the loser, a trade's net KTC is +X for one side
# and -X for the other. Ranking the raw values would report one fact as two
# records — the biggest blowout AND the biggest defeat, always the same game — and
# would fill the bottom of every such board with the mirror images of its top.
# So a mirrored column is ranked over its POSITIVE values only: "highest
# Margin" is the biggest blowout, "lowest Margin" the closest game, each named
# once, from the side that came out ahead.
#
# With ONE exception: a dead-even event — a trade of exactly equal KTC value, a
# tied game — is 0 on both of its rows, so a strictly-positive reduction drops it
# entirely and the board reports the closest NON-even event as the most even one
# ever. Zero is the record at that end, not a missing value, so one row per even
# event is kept (`_even_event_rows`), from the side that sorts first, there being
# no side that came out ahead.
#
# Detected STRUCTURALLY (two_sided_columns), from rows that pair up through a
# counterpart column — not from the shape of the distribution. A distribution
# test would also catch `Change from previous week`, which is symmetric because
# players gain and lose about equally often, and clipping it to positives would
# throw away "biggest drop from last week" — a real record, not a mirror image.
# sheet -> (the row's side, the column naming the other side, the columns that
# identify the shared event). Only sheets whose rows come in sides can mirror.
_MIRROR_PAIRS = {
    "team_week": ("Team", "Opponent", ("Year", "Week")),
    "trades": ("Team", "Team's traded with 1", ("Date", "Season")),
}


def mirrored_columns(df: pd.DataFrame, sheet: str) -> set:
    """The columns of `sheet` that hold one fact from both sides."""
    pair = _MIRROR_PAIRS.get(sheet)
    if not pair or df is None or df.empty or pair[1] not in df.columns:
        return set()
    return set(two_sided_columns(df, pair[0], pair[1], list(pair[2])))


def numeric_series(df: pd.DataFrame, column: str) -> "pd.Series":
    """The column as floats, sentinels ("N/A", "In Progress") dropped. Uses the
    vectorised parser when the column is already numeric — the weekly sheets are
    20k rows deep and a per-cell Python parse over every column is the difference
    between a build step and a coffee break."""
    col = df[column]
    if pd.api.types.is_numeric_dtype(col):
        return pd.to_numeric(col, errors="coerce").dropna()
    return pd.to_numeric(col.map(_to_float), errors="coerce").dropna()


def _even_event_rows(df: pd.DataFrame, sheet: str, s: "pd.Series") -> set:
    """One representative row index per event whose mirrored value is exactly 0.

    An even event has no winning side, so both its rows read 0 and a positive-only
    pool would lose the event altogether — the most even trade in league history
    would be missing from "lowest KTC value difference". Its two rows are the same
    fact, so exactly one is kept: the side whose name sorts first, a choice that
    does not move build to build. A row with no counterpart named (an unpaired
    row on a sheet that mostly pairs) is its own event and is kept as it is.

    Returns an empty set for a sheet with no mirror pairing configured — the
    caller could not have detected the column as mirrored either."""
    pair = _MIRROR_PAIRS.get(sheet)
    if not pair:
        return set()
    entity_col, opp_col, id_cols = pair
    if entity_col not in df.columns or opp_col not in df.columns:
        return set()
    groups: Dict[tuple, list] = {}
    keep = set()
    for idx, r in df.loc[list(s.index[s == 0])].iterrows():
        a, b = str(r[entity_col]), str(r.get(opp_col) or "")
        if not b:
            keep.add(idx)
            continue
        key = tuple(str(r.get(c, "")) for c in id_cols) + tuple(sorted([a, b]))
        groups.setdefault(key, []).append((a, idx))
    for members in groups.values():
        keep.add(sorted(members)[0][1])
    return keep


def rankable_series(df: pd.DataFrame, column: str, mirrored: bool = False,
                    sheet: str = "") -> "pd.Series":
    """`numeric_series`, reduced to one row per event when the column mirrors:
    the positive side, plus one row of every dead-even (0) event."""
    s = numeric_series(df, column)
    if not mirrored:
        return s
    return s[(s > 0) | s.index.isin(_even_event_rows(df, sheet, s))]


# ---------------------------------------------------------------------------
# Rankings (descending: index 0 = highest value; tail = lowest)
# ---------------------------------------------------------------------------
def rank_column(df: pd.DataFrame, entity_col: str, column: str) -> List[dict]:
    """Ordered [{'entity','value'}] high -> low for one column (ties by name)."""
    if column not in df.columns or entity_col not in df.columns:
        return []
    rows = []
    for _, r in df.iterrows():
        v = _to_float(r[column])
        if v is None:
            continue
        rows.append({"entity": str(r[entity_col]), "value": v})
    rows.sort(key=lambda e: (-e["value"], e["entity"]))
    return rows


def competition_ranks(values: Sequence[float], end: str) -> Dict[float, int]:
    """value -> competition ("1224") rank from the watched `end`.

    Tied values share the smallest rank they'd occupy, and the next distinct
    value's rank skips by the count of tied values above it — a two-way tie for
    1st makes the next value 3rd, not 2nd. This is what lets tied rows take up
    the requisite number of the top-N slots."""
    counts = _Counter(values)
    ordered = sorted(counts, reverse=(end == "high"))
    ranks: Dict[float, int] = {}
    pos = 1
    for v in ordered:
        ranks[v] = pos
        pos += counts[v]
    return ranks


def _name_list(names: Sequence[str]) -> str:
    """"X" / "X and Y" / "X, Y and Z" — the way a person would read a short list."""
    names = list(names)
    if not names:
        return ""
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} and {names[1]}"
    return f"{', '.join(names[:-1])} and {names[-1]}"


# The largest tie a "joins a tie" line will report. Joining a tie bigger than
# this (6+ holders including the mover) is not worth a line — the value is too
# common to be news — so it is suppressed entirely (Change 4).
_MAX_JOIN_TIE = 5


def _tie_fits(rank: int, holders: int, window: int) -> bool:
    """A place shared by `holders` rows is a top-`window` place only if the WHOLE
    tie fits inside the window. Competition ranks give a tie the places it takes
    up, so a three-way tie for 4th fills 4th-6th and sits partly off a top-5
    board: "Jalen Royals joins a tie for 4th-highest Rostered consistency
    percentile" named a place three players cannot all hold. So a two-way tie for
    5th, a three-way for 4th, a four-way for 3rd ... is reported nowhere, and a
    tie for 1st still reports up to `window` holders."""
    return rank + max(1, holders) - 1 <= window


def _crossing_detail(joined: bool, others: Sequence[str], passed: Sequence[str],
                     place: str, column: str, value: Optional[float],
                     sheet: str = "", co_movers: Sequence[str] = ()) -> str:
    """Shared phrasing for an all-time / event-board move. The subject — the
    mover, and any `co_movers` that reached the same tie the same week — is the
    caller's (`group()`); this is the predicate.

    joined:  the movers ARRIVED at a value: "joins E and F in a tie for 3rd",
             "join F in a tie for 3rd", or, when nobody held it before them,
             "share 3rd". Every holder is named (a tie that fits a top-5 board
             has at most five).
    passed:  whoever lost a board place to the move, named in full — for a tie,
             the rows it pushed down: ", passing G and H"."""
    val = f" ({_fmt_stat(column, value)})" if value is not None else ""
    column = display_column(column, sheet)
    if joined:
        if others:
            verb = "join" if co_movers else "joins"
            head = f"{verb} {_name_list(others)} in a tie for {place} {column}{val}"
        else:
            head = f"share {place} {column}{val}"
        return head + (f", passing {_name_list(passed)}" if passed else "")
    return f"passes {_name_list(passed)} for {place} {column}{val}"


def _rankings_for(df: pd.DataFrame, entity_col: str,
                  columns: Sequence[str], held: frozenset = frozenset()
                  ) -> Dict[str, List[dict]]:
    """Every column's ranking; `held` entities rank on counting columns only."""
    out: Dict[str, List[dict]] = {}
    sample = df[~df[entity_col].astype(str).isin(held)] \
        if held and entity_col in df.columns else df
    for col in columns:
        ranked = rank_column(df if is_counting_stat(col) else sample, entity_col, col)
        if len(ranked) >= 2:
            out[col] = ranked
    return out


# ---------------------------------------------------------------------------
# Season / week helpers
# ---------------------------------------------------------------------------
def current_season(team_year: pd.DataFrame) -> Optional[int]:
    if "Year" not in team_year.columns:
        return None
    yrs = pd.to_numeric(team_year["Year"], errors="coerce").dropna()
    return int(yrs.max()) if len(yrs) else None


def weeks_completed(team_week: pd.DataFrame, season: int) -> int:
    """Distinct completed weeks for `season` (the build only writes a week once
    it is final, per the Phase 5E freshness gate). 0 => offseason."""
    if team_week.empty or "Year" not in team_week.columns or "Week" not in team_week.columns:
        return 0
    sub = team_week[pd.to_numeric(team_week["Year"], errors="coerce") == season]
    weeks = pd.to_numeric(sub["Week"], errors="coerce").dropna().unique()
    return int(len(weeks))


# ---------------------------------------------------------------------------
# Snapshot (all-time rankings, for week-over-week diffing)
# ---------------------------------------------------------------------------
def build_snapshot(
    player_all_time: pd.DataFrame,
    team_all_time: pd.DataFrame,
    team_year: pd.DataFrame,
    team_week: pd.DataFrame,
    league_all_time: Optional[pd.DataFrame] = None,
    captured_at: Optional[datetime] = None,
    inputs_fingerprint: Optional[str] = None,
    held_players: Optional[Iterable[str]] = None,
) -> dict:
    """`held_players` (`BoardGate.held_rookies`) rank only on counting columns —
    whose low end `diff_snapshots` then ignores for them — and are named in the
    meta, so the week they are let go their places read as arrivals."""
    captured_at = captured_at or datetime.now(timezone.utc)
    season = current_season(team_year)
    weeks = weeks_completed(team_week, season) if season is not None else 0
    # EVERY numeric column ranks — no volatility filter. #380 excluded the
    # league-relative and rolling families here on the theory that they drift a
    # hair on every recompute and would flip a rank-boundary tie into a phantom
    # move; in practice a rank-boundary flip is a real change of order and the
    # columns it hides (the skill family, Luck, the KTC windows) are ones a
    # reader wants to hear about. The weekly AUDIT still exempts them — there the
    # question is "did a frozen historical value move", which is a different one.
    p_cols = discover_numeric_columns(player_all_time, "Player")
    t_cols = discover_numeric_columns(team_all_time, "Team")
    meta = {
        "captured_at": captured_at.isoformat(),
        "season": season,
        "weeks_completed": weeks,
    }
    held = sorted({str(p) for p in (held_players or ())})
    if held:
        meta["held_players"] = held
    if inputs_fingerprint:
        # What this build was made FROM (code + curated data). Next week's digest
        # compares it to tell a week with an edit from one without — see
        # `edit_fingerprint` and `new_data_since`.
        meta["inputs_fingerprint"] = inputs_fingerprint
    return {
        "meta": meta,
        "players": _rankings_for(player_all_time, "Player", p_cols, held=set(held)),
        "teams": _rankings_for(team_all_time, "Team", t_cols),
        "league_milestones": league_milestone_values(
            league_all_time if league_all_time is not None else pd.DataFrame()),
    }


def is_in_season(snapshot: dict) -> bool:
    return int(snapshot.get("meta", {}).get("weeks_completed", 0) or 0) >= 1


